#!/usr/bin/env python3
"""Writes samples/opengl/gl.h from the Khronos registry: every GL command and
constant the samples name, and nothing else.

    samples/opengl/gl_header.py

Run it after a sample starts using a command or constant gl.h lacks. The
registry is the one tools/fetch_khronos_registries.py pins, so the values are
the ones the ICD's generated protocol was built from.
"""
import pathlib
import re
import xml.etree.ElementTree as ElementTree

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
REGISTRY = ROOT / "third_party" / "khronos" / "gl.xml"

PREAMBLE = """// THIS FILE IS GENERATED by samples/opengl/gl_header.py from the Khronos
// registry: the GL commands and constants the samples use. Do not edit it;
// name the new command or constant in a sample and run the script again.
#pragma once

#include <stddef.h>
#include <stdint.h>

#if defined(_WIN32)
#define SAMPLES_GL_API __stdcall
#else
#define SAMPLES_GL_API
#endif

typedef unsigned int GLenum;
typedef unsigned char GLboolean;
typedef unsigned int GLbitfield;
typedef void GLvoid;
typedef int8_t GLbyte;
typedef uint8_t GLubyte;
typedef int16_t GLshort;
typedef uint16_t GLushort;
typedef int GLint;
typedef unsigned int GLuint;
typedef int GLsizei;
typedef float GLfloat;
typedef double GLdouble;
typedef char GLchar;
typedef ptrdiff_t GLintptr;
typedef ptrdiff_t GLsizeiptr;
typedef int64_t GLint64;
typedef uint64_t GLuint64;
typedef struct __GLsync *GLsync;
typedef void(SAMPLES_GL_API *GLDEBUGPROC)(GLenum source, GLenum type, GLuint id, GLenum severity, GLsizei length,
                                          const GLchar *message, const void *userParam);
"""


def used_names():
    commands, constants = set(), set()
    for path in list(HERE.glob("*.cpp")) + list(HERE.glob("*.h")):
        if path.name == "gl.h":
            continue
        text = path.read_text()
        commands.update(re.findall(r"\b(gl[A-Z]\w*)\s*\(", text))
        constants.update(re.findall(r"\b(GL_[A-Z0-9_]+)\b", text))
    return commands, constants


def registry():
    root = ElementTree.parse(REGISTRY).getroot()
    values = {}
    for enums in root.iter("enums"):
        for enum in enums.findall("enum"):
            if enum.get("api") not in (None, "gl"):
                continue
            suffix = {"u": "u", "ull": "ull"}.get(enum.get("type", ""), "")
            values.setdefault(enum.get("name"), enum.get("value") + suffix)
    commands = {}
    for command in root.find("commands").findall("command"):
        proto = command.find("proto")
        name = proto.find("name").text
        returned = "".join(proto.itertext())[: -len(name)].strip()
        params = []
        for param in command.findall("param"):
            params.append(" ".join("".join(param.itertext()).split()))
        commands[name] = (returned, ", ".join(params) if params else "void")
    return commands, values


def main():
    wanted_commands, wanted_constants = used_names()
    commands, values = registry()
    lines = [PREAMBLE]
    for name in sorted(wanted_constants):
        if name in values:
            lines.append(f"#define {name} {values[name]}")
    lines.append("")
    lines.append("// X(return type, name, parameters) for every command the samples call.")
    lines.append("#define SAMPLES_GL_COMMANDS(X) \\")
    known = sorted(name for name in wanted_commands if name in commands)
    for name in known:
        returned, params = commands[name]
        lines.append(f"    X({returned}, {name}, ({params})) \\")
    lines.append("")
    lines.append("namespace samples {")
    lines.append("#define SAMPLES_GL_DECLARE(returned, name, params) extern returned(SAMPLES_GL_API *name) params;")
    lines.append("SAMPLES_GL_COMMANDS(SAMPLES_GL_DECLARE)")
    lines.append("#undef SAMPLES_GL_DECLARE")
    lines.append("}  // namespace samples")
    (HERE / "gl.h").write_text("\n".join(lines) + "\n")
    unknown = sorted(name for name in wanted_commands if name not in commands)
    missing = sorted(name for name in wanted_constants if name not in values)
    for name in unknown + missing:
        print(f"not in the registry: {name}")


if __name__ == "__main__":
    main()
