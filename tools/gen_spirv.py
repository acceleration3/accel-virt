#!/usr/bin/env python3
"""Compile the guest suite's GLSL into SPIR-V headers, or check the committed ones.

Every *.comp, *.vert and *.frag in src/guest/suite/shaders/ is compiled with
`glslangValidator -V` into <name>_spv.hpp beside it: the module as a constexpr
uint32_t array and its word count, in namespace av. The guest suite is
freestanding and pushed alone into a guest, so the module is compiled in.

  gen_spirv.py [--shaders DIR] [--check]

--check writes nothing and fails naming every header that differs from what
would be written, is missing, or has no source left. It fails as well when
glslangValidator is absent: a check that cannot compile has checked nothing.
"""
import argparse
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SHADERS = ROOT / "src" / "guest" / "suite" / "shaders"
STAGES = (".comp", ".vert", ".frag")
HEADER_SUFFIX = "_spv.hpp"
COMPILER = "glslangValidator"
SPIRV_MAGIC = 0x07230203
WORDS_PER_LINE = 8


class Refused(Exception):
    """A shader that cannot become a header; the message names it."""


def sources_in(shaders):
    """{header path: source path}, refusing two sources that would write one header."""
    headers = {}
    for source in sorted(path for path in shaders.iterdir() if path.suffix in STAGES):
        header = shaders / f"{source.stem}{HEADER_SUFFIX}"
        if header in headers:
            raise Refused(f"{headers[header].name} and {source.name} would both write {header.name}")
        headers[header] = source
    return headers


def words_of(source, compiler, scratch):
    """The SPIR-V glslangValidator makes of `source`, as little-endian words."""
    output = scratch / f"{source.name}.spv"
    compiled = subprocess.run([compiler, "-V", "-o", str(output), source.name], cwd=str(source.parent),
                              capture_output=True, text=True)
    if compiled.returncode != 0:
        detail = (compiled.stdout + compiled.stderr).strip()
        raise Refused(f"{source.name}: {COMPILER} failed\n{detail}")
    module = output.read_bytes() if output.is_file() else b""
    if len(module) < 4 or len(module) % 4:
        raise Refused(f"{source.name}: {COMPILER} wrote {len(module)} bytes, not whole SPIR-V words")
    words = struct.unpack(f"<{len(module) // 4}I", module)
    if words[0] != SPIRV_MAGIC:
        raise Refused(f"{source.name}: {COMPILER} wrote magic 0x{words[0]:08x}, not SPIR-V")
    return words


def header_text(source, words):
    name = f"{source.stem}_spv"
    guard = f"AV_{name.upper()}_HPP"
    lines = [f"    {', '.join(f'0x{word:08x}' for word in words[start:start + WORDS_PER_LINE])},"
             for start in range(0, len(words), WORDS_PER_LINE)]
    return (f"/* SPIR-V compiled from {source.name} by glslangValidator -V. Generated by\n"
            f" * tools/gen_spirv.py; edit the GLSL and regenerate, never this file. */\n"
            f"#ifndef {guard}\n"
            f"#define {guard}\n"
            f"\n"
            f"#include <stdint.h>\n"
            f"\n"
            f"namespace av {{\n"
            f"\n"
            f"inline constexpr uint32_t {name}[] = {{\n"
            + "\n".join(lines) + "\n"
            f"}};\n"
            f"\n"
            f"inline constexpr uint32_t {name}_words = {len(words)}u;\n"
            f"\n"
            f"}}  // namespace av\n"
            f"\n"
            f"#endif\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--shaders", type=pathlib.Path, default=DEFAULT_SHADERS)
    parser.add_argument("--check", action="store_true",
                        help="write nothing; fail if a committed header is not what would be written")
    arguments = parser.parse_args(argv)

    compiler = shutil.which(COMPILER)
    if compiler is None:
        print(f"spirv: {COMPILER} not found on PATH; it compiles {arguments.shaders}", file=sys.stderr)
        return 1
    try:
        headers = sources_in(arguments.shaders)
        with tempfile.TemporaryDirectory() as scratch:
            wanted = {header: header_text(source, words_of(source, compiler, pathlib.Path(scratch)))
                      for header, source in headers.items()}
    except Refused as refused:
        print(f"spirv: {refused}", file=sys.stderr)
        return 1
    stale = sorted(path for path in arguments.shaders.glob(f"*{HEADER_SUFFIX}") if path not in wanted)

    if arguments.check:
        problems = [f"{header} differs from what {headers[header].name} compiles to"
                    if header.is_file() else f"{header} is missing"
                    for header, text in wanted.items()
                    if not header.is_file() or header.read_text() != text]
        problems += [f"{header} has no source" for header in stale]
        for problem in problems:
            print(f"spirv: {problem}; run tools/gen_spirv.py", file=sys.stderr)
        if problems:
            return 1
        print(f"spirv: {len(wanted)} headers match their sources")
        return 0

    for header in stale:
        header.unlink()
        print(f"spirv: removed {header}")
    for header, text in wanted.items():
        header.write_text(text)
        print(f"spirv: {header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
