#!/usr/bin/env python3
"""The Direct3D 9 device-function table's thunks, from the WDK's own header.

The table d3d9.dll hands a user-mode driver is D3DDDI_DEVICEFUNCS (d3dumddi.h):
some 130 function pointers, each typed by its own PFN typedef. As for Direct3D
11 (tools/gen_d3d11_ddi.py), clang reads the kit's header for the Windows
target and this writes, from the types it reports:

  src/um/d3d/generated/d3d9_device_thunks.cpp   one ABI thunk per slot, each one
                                                 line into D3d9Device, and the
                                                 function that fills the table
  src/um/d3d/generated/d3d9_device_ddi.inc       the D3d9Device methods they
                                                 call, included in its class

Every slot is the device's own: a Direct3D 9 device is named by the HANDLE
CreateDevice handed back, which is the D3d9Device itself.

    tools/gen_d3d9_ddi.py            # regenerate
    tools/gen_d3d9_ddi.py --check    # fail if the committed files differ
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "um" / "d3d" / "generated"
KIT = ROOT / "third_party" / "windows-kit"
TABLE = "D3DDDI_DEVICEFUNCS"

PROBE = """#include <windows.h>
typedef _Return_type_success_(return >= 0) LONG NTSTATUS;
#include <d3d9types.h>
#include <d3d9caps.h>
#include <d3dumddi.h>
D3DDDI_DEVICEFUNCS *probe;
"""

HEADER = "// THIS FILE IS GENERATED BY tools/gen_d3d9_ddi.py FROM THE WDK'S d3dumddi.h. DO NOT EDIT.\n"


def dump():
    with tempfile.TemporaryDirectory() as scratch:
        source = pathlib.Path(scratch) / "probe.cpp"
        source.write_text(PROBE)
        command = ["clang-cl", "/GR-", "/EHs-c-", "/Zl", "/X", "/D_AMD64_", "/DAMD64", "/D_WIN64",
                   "/DWIN32_LEAN_AND_MEAN", "/DNOMINMAX", f"/clang:-ivfsoverlay{KIT}/overlay.yaml",
                   "-imsvc/windows-kit/km/crt", "-imsvc/windows-kit/um", "-imsvc/windows-kit/sdk-shared",
                   "-imsvc/windows-kit/wdk-shared", "-clang:-std=c++23", "--target=x86_64-pc-windows-msvc", "/Zs",
                   "-Xclang", "-ast-dump=json", "-Xclang", f"-ast-dump-filter={TABLE}", str(source)]
        text = subprocess.run(command, capture_output=True, text=True, check=True).stdout
    decoder = json.JSONDecoder()
    at = 0
    while at < len(text):
        while at < len(text) and text[at].isspace():
            at += 1
        if at >= len(text):
            break
        node, at = decoder.raw_decode(text, at)
        if node.get("kind") == "CXXRecordDecl" and node.get("completeDefinition") and node.get("name") == "_" + TABLE:
            return [field for field in node["inner"] if field["kind"] == "FieldDecl"]
    raise SystemExit(f"clang reported no definition of {TABLE}")


def split_top(parameters):
    depth, current, out = 0, "", []
    for ch in parameters:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


SIGNATURE = re.compile(r"^(?P<ret>.+?) \(\*\)\((?P<params>.*)\)$")


def snake(name):
    name = name[len("pfn"):]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def entries(fields):
    out = []
    for field in fields:
        if RESERVED.match(field["name"]) or field["name"] in NULL_SLOTS:
            continue
        signature = field["type"].get("desugaredQualType", field["type"]["qualType"])
        signature = signature.replace(" __attribute__((stdcall))", "")
        matched = SIGNATURE.match(signature)
        if not matched:
            raise SystemExit(f"{field['name']}: cannot read {signature!r}")
        parameters = split_top(matched["params"])
        if not parameters or parameters[0] != "HANDLE":
            raise SystemExit(f"{field['name']}: first parameter is {parameters[:1]}, not the device")
        out.append((field["name"], field["type"]["qualType"], matched["ret"], parameters))
    return out


# Slots the driver answers rather than the device: a device cannot give
# itself back to the pool it lives in.
ROOT_SLOTS = {"pfnDestroyDevice": "destroy_device9"}
# Reserved slots, typed void *, which nothing calls.
RESERVED = re.compile(r"^pfnReserved")
# Slots left NULL on purpose, because d3d9.dll reads a NULL as "feature off"
# and a filled slot as a promise (docs/research/d3d9/reverse-engineering.md
# §1.4, §3.3): capture, async locks, the video, authenticated-channel, crypto
# and content-protection groups (each all-or-nothing), CreateResource2 and the
# 1-suffixed blts (the driver answers DriverVersion 0x2003, where the old slots
# are the ones used and filling both fails CreateDevice above 0x4001), the
# WDDM 1.3 present path, residency trimming and the WDDM 2.1 sync DDIs.
NULL_SLOTS = {
    "pfnGetCaptureAllocationHandle", "pfnCaptureToSysMem", "pfnLockAsync", "pfnUnlockAsync", "pfnRename",
    "pfnCreateVideoProcessor", "pfnSetVideoProcessBltState", "pfnGetVideoProcessBltStatePrivate",
    "pfnSetVideoProcessStreamState", "pfnGetVideoProcessStreamStatePrivate", "pfnVideoProcessBltHD",
    "pfnDestroyVideoProcessor", "pfnCreateAuthenticatedChannel", "pfnAuthenticatedChannelKeyExchange",
    "pfnQueryAuthenticatedChannel", "pfnConfigureAuthenticatedChannel", "pfnDestroyAuthenticatedChannel",
    "pfnCreateCryptoSession", "pfnCryptoSessionKeyExchange", "pfnDestroyCryptoSession", "pfnEncryptionBlt",
    "pfnGetPitch", "pfnStartSessionKeyRefresh", "pfnFinishSessionKeyRefresh", "pfnGetEncryptionBltKey",
    "pfnDecryptionBlt", "pfnCreateResource2", "pfnVolBlt1", "pfnBufBlt1", "pfnTexBlt1", "pfnFlush1",
    "pfnCheckCounterInfo", "pfnCheckCounter", "pfnUpdateSubresourceUP", "pfnPresent1", "pfnSetMarker",
    "pfnSetMarkerMode", "pfnTrimResidencySet", "pfnAcquireResource", "pfnReleaseResource",
}


def ret_type(ret):
    return {"void": "VOID", "int": "BOOL"}.get(ret, ret)


def thunks(table):
    lines = [HEADER, "/* The ABI boundary C requires: the runtime calls each slot with the device", " * handle CreateDevice handed back and nothing else, so each thunk is one line", " * into the device that handle is. */",
             '#include "core/trace/function_scope.hpp"', '#include "icd/d3d/umd_binding.hpp"', '#include "icd/d3d/umd_root.hpp"', '#include "um/d3d/d3d9_ddi.hpp"', '#include "um/d3d/d3d9_device.hpp"', '#include "um/d3d/device_call.hpp"', '#include "um/d3d/d3d9_tables.hpp"', "", "namespace av::d3d9 {", "", "namespace {", ""]
    for name, _pfn, ret, parameters in table:
        names = ["device"] + [f"a{index}" for index in range(1, len(parameters))]
        declared = ", ".join(f"{kind} {label}" for kind, label in zip(parameters, names))
        arguments = ", ".join(names[1:])
        keyword = "" if ret == "void" else "return "
        lines.append(f"extern \"C\" {ret_type(ret)} APIENTRY avumd_d3d9_{name[3:]}({declared})")
        if name in ROOT_SLOTS:
            lines.append(f"{{ {keyword}d3d::umd_binding.root().{ROOT_SLOTS[name]}(device); }}")
            lines.append("")
            continue
        lines.append(f"{{ {keyword}d3d::DeviceCall<D3d9Device>(*static_cast<D3d9Device *>(device)).device()"
                     f".{snake(name)}({arguments}); }}")
        lines.append("")
    lines += ["}  // namespace", "", f"void fill_device_funcs9({TABLE} &table)", "{", '    AV_SCOPE("fill_device_funcs9");']
    for name, _pfn, _ret, _parameters in table:
        lines.append(f"    table.{name} = &avumd_d3d9_{name[3:]};")
    lines += ["}", "", "}  // namespace av::d3d9", ""]
    return "\n".join(lines)


def methods(table):
    lines = [HEADER, "// Included inside class D3d9Device: one method per device-table slot.", ""]
    for name, _pfn, ret, parameters in table:
        if name in ROOT_SLOTS:
            continue
        declared = ", ".join(parameters[1:])
        lines.append(f"{ret_type(ret)} {snake(name)}({declared});")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table = entries(dump())
    files = {"d3d9_device_thunks.cpp": thunks(table), "d3d9_device_ddi.inc": methods(table)}
    if args.check:
        differ = [name for name, text in files.items()
                  if not (OUT / name).exists() or (OUT / name).read_text() != text]
        for name in differ:
            print(f"generated: {name} differs from what tools/gen_d3d9_ddi.py writes", file=sys.stderr)
        return 1 if differ else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"gen_d3d9_ddi: {len(table)} slots -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
