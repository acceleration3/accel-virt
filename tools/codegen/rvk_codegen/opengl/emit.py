"""The generated OpenGL half of the wire.

Six files come out of here.

``gl_protocol_ids.h``    one id per command, never moved once assigned
``gl_command_names``     id back to name, for logs
``gl_sizes.h``           how many values an enum answers with, and how
                         wide an index type is: the two questions the
                         registry poses as COMPSIZE and does not answer
``gl_dispatch_client``   what the guest driver calls
``gl_dispatch_server``   what the host reads, and what it calls
``gl_real_dispatch.h``   the host entry points, loaded by name

The shape follows the OpenCL generator, with one difference that runs
through all of it: a command with nothing to answer does not wait. It
goes on the ring and the caller returns. Ordering is the ring's, so a
later command that does wait sees everything before it.
"""

from __future__ import annotations

from pathlib import Path

from .model import Command, LengthKind, Param, Registry, Role

HEADER = """// Generated by rvk-codegen-gl. Do not edit.
//
// Source: gl.xml, wgl.xml and codegen/gl_profile.toml.
"""

# Types written as they are rather than as a varint: a float that goes
# through a varint is a float that has been rounded.
POD_SCALARS = {"GLfloat", "GLclampf", "GLdouble", "GLclampd", "GLhalf"}


def _is_pod_scalar(base: str) -> bool:
    return base in POD_SCALARS


def _ret_kind(cmd: Command) -> str:
    ret = cmd.return_type
    if ret.base == "void" and ret.pointer_depth == 0:
        return "void"
    if ret.base == "GLsync":
        return "sync"
    if ret.pointer_depth > 0:
        # const GLubyte* from glGetString and friends. There is no
        # pointer to hand over, so the text comes back as bytes and the
        # guest keeps its own copy.
        if ret.base in ("GLubyte", "GLchar", "char"):
            return "string"
        return "pointer"
    return "scalar"


# ---------------------------------------------------------------------
# Signatures
# ---------------------------------------------------------------------

# A read states the room it has: bufSize is the caller's answer to how
# many bytes there are, and asking again is a second answer to the same
# question and somewhere for the two to disagree.
#
# A compressed upload's imageSize is not that answer. It says how long
# the image is, not where in the caller's memory it begins: with the
# unpack skips set the host starts whole rows of blocks in, and those
# rows are the caller's bytes as much as the image is. So the driver
# works the length out — see compressed_bytes — and imageSize crosses
# as what it is, an argument of the call.
STATED_SIZE_PARAMS = ("bufSize",)


def _stated_size(cmd: Command) -> str | None:
    names = {p.name for p in cmd.params}
    for stated in STATED_SIZE_PARAMS:
        if stated in names:
            return stated
    return None


def _pixel_bytes_expr(cmd: Command, p: Param) -> str:
    """The byte count of a pixel parameter, in the client's scope."""
    stated = _stated_size(cmd)
    if stated is not None:
        return f"static_cast<std::size_t>({stated})"
    return f"{p.name}_bytes"


def fail_for(cmd: Command) -> str:
    """What a client entry point returns when it cannot send."""
    return {"void": "return;", "scalar": "return 0;", "sync": "return 0;",
            "string": "return false;", "pointer": "return nullptr;"}[_ret_kind(cmd)]


def _client_params(cmd: Command, defaults: bool = False) -> list[str]:
    out = []
    for p in cmd.params:
        if p.role is Role.IGNORED:
            continue
        if p.role is Role.SYNC:
            out.append(f"std::uint64_t {p.name}")
        elif p.role is Role.BUFFER_OFFSET:
            out.append(f"std::uint64_t {p.name}")
        elif p.role is Role.OFFSET_ARRAY:
            out.append(f"const std::uint64_t* {p.name}")
        elif p.role in (Role.PIXELS_IN, Role.PIXELS_OUT):
            const = "const " if p.role is Role.PIXELS_IN else ""
            out.append(f"{const}void* {p.name}")
            if _stated_size(cmd) is None:
                out.append(f"std::size_t {p.name}_bytes")
            # With a pixel buffer bound the pointer is an offset into
            # it, not an address in the caller — the same argument
            # meaning two different things is what the specification
            # says, so the wire has to be told which one it got. A
            # caller with no pixel buffer says nothing and gets the
            # address it always got.
            out.append(f"bool {p.name}_is_offset" +
                       (" = false" if defaults else ""))
        else:
            out.append(f"{p.type.cpp()} {p.name}")
    return out


def _client_return(cmd: Command) -> str:
    kind = _ret_kind(cmd)
    if kind == "void":
        return "void"
    if kind == "sync":
        return "std::uint64_t"
    if kind == "string":
        return "bool"
    return cmd.return_type.cpp()


def _client_signature(cmd: Command, defaults: bool = False) -> str:
    # The transport is rvk_t rather than t because GL has parameters
    # called t: glTexCoord2f(s, t) is one, and a transport named the
    # same thing shadows it in the very expression that needs both.
    params = ["::rvk::protocol::Transport& rvk_t"] + _client_params(cmd, defaults)
    if _ret_kind(cmd) == "string":
        params.append("std::string* out")
    return f"{_client_return(cmd)} rvk_{cmd.name}({', '.join(params)})"


# ---------------------------------------------------------------------
# How long is it
# ---------------------------------------------------------------------

def _count_expr(p: Param) -> str:
    """C for how many elements the parameter has, in the caller's scope."""
    length = p.length
    if length is None:
        return "0"
    if length.kind is LengthKind.FIXED:
        return str(length.count)
    if length.kind in (LengthKind.PARAM, LengthKind.EXPR):
        return f"static_cast<std::size_t>({length.text})"
    if length.kind is LengthKind.STRING:
        return f"({p.name} != nullptr ? std::strlen(reinterpret_cast<const char*>({p.name})) : 0)"
    if length.kind is LengthKind.PNAME:
        # The transport-taking overload: a few of these are lists whose
        # length only the driver knows, and a table that guessed too
        # high would write past the end of the caller's array.
        return f"::av::glproto::pname_count(rvk_t, {length.reads[0]})"
    if length.kind is LengthKind.TYPED_COUNT:
        count, type_name = length.reads
        return (f"(static_cast<std::size_t>({count}) * "
                f"::av::glproto::type_size({type_name}))")
    raise AssertionError(f"no count for {p.name}: {length.kind}")


def _bytes_expr(p: Param) -> str:
    if p.length is not None and p.length.kind is LengthKind.TYPED_COUNT:
        # Already a byte count: an index array is counted in elements of
        # a type the registry names rather than in elements of its own.
        return _count_expr(p)
    return f"({_count_expr(p)} * sizeof({p.type.base}))"


# ---------------------------------------------------------------------
# ids and names
# ---------------------------------------------------------------------

def emit_ids(reg: Registry, out_dir: Path) -> None:
    out = [HEADER, "#pragma once\n", "#include <cstdint>\n",
           "namespace av::glproto {\n"]
    for cmd in reg.commands.values():
        out.append(f"inline constexpr std::uint32_t kCmd_{cmd.name} = "
                   f"0x{cmd.command_id:08x};")
    out += ["", "}  // namespace av::glproto", ""]
    (out_dir / "gl_protocol_ids.h").write_text("\n".join(out))


def emit_names(reg: Registry, out_dir: Path) -> None:
    h = [HEADER, "#pragma once\n", "#include <cstdint>\n",
         "namespace av::glproto {\n",
         "const char* cmd_id_to_string(std::uint32_t cmd_id) noexcept;\n",
         "}  // namespace av::glproto", ""]
    c = [HEADER, '#include "gl_command_names.h"\n',
         '#include "gl_protocol_ids.h"\n',
         "namespace av::glproto {\n",
         "const char* cmd_id_to_string(std::uint32_t cmd_id) noexcept {",
         "    switch (cmd_id) {"]
    for cmd in reg.commands.values():
        c.append(f'        case kCmd_{cmd.name}: return "{cmd.name}";')
    c += ['        default: return "unknown";', "    }", "}", "",
          "}  // namespace av::glproto", ""]
    (out_dir / "gl_command_names.h").write_text("\n".join(h))
    (out_dir / "gl_command_names.cpp").write_text("\n".join(c))


# ---------------------------------------------------------------------
# The two questions COMPSIZE poses
# ---------------------------------------------------------------------

def emit_sizes(reg: Registry, out_dir: Path) -> None:
    out = [HEADER, "#pragma once\n",
           "#include <cstddef>",
           "#include <cstdint>\n",
           "namespace av::glproto {\n",
           "// How many values a query with this enum answers with.",
           "//",
           "// The registry says COMPSIZE(pname) and stops. Almost every",
           "// enum answers with one value; the ones that do not are",
           "// listed in the profile, and both sides read this table, so",
           "// they agree about how much came back.",
           "[[nodiscard]] inline std::size_t pname_count(std::uint32_t pname) noexcept {",
           "    switch (pname) {"]
    written: dict[int, tuple[str, int]] = {}
    for name, count in sorted(reg.pname_counts.items()):
        value = _enum_value(name)
        if value in written:
            # Two spellings of one enum. They must agree about the
            # count, because the wire only sees the number.
            first, first_count = written[value]
            if first_count != count:
                raise AssertionError(
                    f"{name} and {first} are the same enum with different "
                    f"counts ({count} and {first_count})")
            out[-1] += f", {name}"
            continue
        written[value] = (name, count)
        out.append(f"        case 0x{value:04X}: return {count};  // {name}")
    out += ["        default: return 1;",
            "    }",
            "}",
            "",
            "// How wide one element of an index or vertex array is.",
            "[[nodiscard]] inline std::size_t type_size(std::uint32_t type) noexcept {",
            "    switch (type) {",
            "        case 0x1400: return 1;  // GL_BYTE",
            "        case 0x1401: return 1;  // GL_UNSIGNED_BYTE",
            "        case 0x1402: return 2;  // GL_SHORT",
            "        case 0x1403: return 2;  // GL_UNSIGNED_SHORT",
            "        case 0x1404: return 4;  // GL_INT",
            "        case 0x1405: return 4;  // GL_UNSIGNED_INT",
            "        case 0x1406: return 4;  // GL_FLOAT",
            "        case 0x140A: return 8;  // GL_DOUBLE",
            "        case 0x140B: return 2;  // GL_HALF_FLOAT",
            "        default: return 4;",
            "    }",
            "}",
            "",
            "}  // namespace av::glproto", ""]
    (out_dir / "gl_sizes.h").write_text("\n".join(out))


_ENUM_VALUES: dict[str, int] = {}


def _enum_value(name: str) -> int:
    return _ENUM_VALUES.get(name, 0)


# ---------------------------------------------------------------------
# The guest's side
# ---------------------------------------------------------------------

def _lease_for_write(name: str, out: list[str], guard: str) -> None:
    out.append(f"    ::rvk::client::BlobArena::Lease {name}_lease{{}};")
    out.append(f"    bool {name}_via_blob = false;")
    out.append(f"    if ({guard} &&")
    out.append(f"        {name}_want >= ::av::glproto::kPixelBlobFloor) {{")
    out.append("        auto& rvk_blobs = ::rvk::client::BlobArena::for_transport(rvk_t);")
    out.append("        if (rvk_blobs.ready()) {")
    out.append(f"            {name}_lease = rvk_blobs.take({name}_want);")
    out.append(f"            if ({name}_lease.ok()) {{")
    out.append(f"                std::memcpy({name}_lease.data, {name}, {name}_want);")
    out.append(f"                {name}_via_blob = true;")
    out.append("            }")
    out.append("        }")
    out.append("    }")


def _write_leases(cmd: Command) -> list[str]:
    return [p.name for p in cmd.params
            if p.role is Role.PIXELS_IN or p.role is Role.ARRAY_IN]


def _hand_back_leases(cmd: Command, out: list[str], sent: bool,
                      indent: str = "    ") -> None:
    for name in _write_leases(cmd):
        out.append(f"{indent}if ({name}_via_blob) {{")
        out.append(f"{indent}    ::rvk::client::BlobArena::for_transport(rvk_t)")
        if sent:
            out.append(f"{indent}        .retire_after_last({name}_lease);")
        else:
            out.append(f"{indent}        .give_back({name}_lease);")
        out.append(f"{indent}}}")


def _encode_param(cmd: Command, p: Param, out: list[str]) -> None:
    name = p.name
    if p.role is Role.IGNORED:
        return
    if p.role is Role.SCALAR:
        if _is_pod_scalar(p.type.base):
            out.append(f"    rvk_b.write_pod<{p.type.base}>({name});")
        else:
            out.append(f"    rvk_b.write_varint(static_cast<std::uint64_t>({name}));")
        return
    if p.role in (Role.SYNC, Role.BUFFER_OFFSET):
        out.append(f"    rvk_b.write_pod<std::uint64_t>({name});")
        return
    if p.role is Role.OFFSET_ARRAY:
        out.append(f"    rvk_b.write_pod<std::uint8_t>({name} != nullptr ? 1 : 0);")
        out.append(f"    if ({name} != nullptr) {{")
        out.append(f"        const std::size_t rvk_n = {_count_expr(p)};")
        out.append("        rvk_b.write_varint(static_cast<std::uint64_t>(rvk_n));")
        out.append("        for (std::size_t rvk_i = 0; rvk_i < rvk_n; ++rvk_i) {")
        out.append(f"            rvk_b.write_pod<std::uint64_t>({name}[rvk_i]);")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.PIXELS_IN:
        size = _pixel_bytes_expr(cmd, p)
        out.append(f"    const std::size_t {name}_want = static_cast<std::size_t>({size});")
        _lease_for_write(name, out, guard=f"!{name}_is_offset && {name} != nullptr")
        out.append(f"    rvk_b.write_pod<std::uint8_t>("
                   f"{name}_is_offset ? 2 : ({name}_via_blob ? 3 : "
                   f"({name} != nullptr ? 1 : 0)));")
        out.append(f"    if ({name}_is_offset) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>("
                   f"reinterpret_cast<std::uintptr_t>({name})));")
        out.append(f"    }} else if ({name}_via_blob) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_lease.offset));")
        out.append(f"    }} else if ({name} != nullptr) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append(f"        if ({name}_want != 0) rvk_b.write({name}, {name}_want);")
        out.append("    }")
        return
    if p.role is Role.PIXELS_OUT:
        size = _pixel_bytes_expr(cmd, p)
        # A read big enough to be worth a lease goes through the blob.
        #
        # The alternative is the reply slot, and the reply slot is
        # 64 KiB: a 640x480 frame is nineteen synchronous fetches, each
        # one a command out and an answer back, for bytes that both
        # sides already map. Through the blob the host writes the
        # pixels where this side can read them and the answer carries
        # nothing at all.
        #
        # Below a page it is not worth it — the allocator rounds to
        # one, so a four-byte read would take 4096 and a round trip to
        # give it back, which is worse than the reply slot it replaced.
        out.append(f"    const std::size_t {name}_want = static_cast<std::size_t>({size});")
        out.append(f"    ::rvk::client::BlobArena::Lease {name}_lease{{}};")
        out.append(f"    bool {name}_via_blob = false;")
        if not cmd.is_async:
            out.append(f"    if (!{name}_is_offset && {name} != nullptr &&")
            out.append(f"        {name}_want >= ::av::glproto::kPixelBlobFloor) {{")
            out.append("        auto& rvk_blobs = ::rvk::client::BlobArena::for_transport(rvk_t);")
            out.append("        if (rvk_blobs.ready()) {")
            out.append(f"            {name}_lease = rvk_blobs.take({name}_want);")
            out.append(f"            {name}_via_blob = {name}_lease.ok();")
            # Cleared before the host writes into it.
            #
            # A read is allowed to ask for more than there is: a caller
            # may read a region larger than the framebuffer, and what
            # lands outside it is undefined. Undefined has to mean
            # zero here rather than whatever the arena last held,
            # because the arena last held somebody else's pixels — so
            # the alternative is handing an application another
            # program's frame, and a picture that changes with what ran
            # before it. The host writes zeros there, and this is how
            # it looks like the host.
            out.append(f"            if ({name}_via_blob) "
                       f"std::memset({name}_lease.data, 0, {name}_want);")
            out.append("        }")
            out.append("    }")
        out.append(f"    rvk_b.write_pod<std::uint8_t>(")
        out.append(f"        {name}_is_offset ? 2 : ({name}_via_blob ? 3 : "
                   f"({name} != nullptr ? 1 : 0)));")
        out.append(f"    if ({name}_is_offset) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>("
                   f"reinterpret_cast<std::uintptr_t>({name})));")
        out.append(f"    }} else if ({name}_via_blob) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_lease.offset));")
        out.append(f"    }} else if ({name} != nullptr) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append("    }")
        return
    if p.role is Role.STRING_IN:
        out.append(f"    rvk_b.write_pod<std::uint8_t>({name} != nullptr ? 1 : 0);")
        out.append(f"    if ({name} != nullptr) {{")
        out.append(f"        const std::size_t rvk_n = {_count_expr(p)};")
        out.append("        rvk_b.write_varint(static_cast<std::uint64_t>(rvk_n));")
        out.append(f"        if (rvk_n != 0) rvk_b.write({name}, rvk_n);")
        out.append("    }")
        return
    if p.role is Role.STRING_ARRAY_IN:
        count = _count_expr(p)
        out.append(f"    rvk_b.write_pod<std::uint8_t>({name} != nullptr ? 1 : 0);")
        out.append(f"    if ({name} != nullptr) {{")
        out.append(f"        const std::size_t rvk_n = {count};")
        out.append("        rvk_b.write_varint(static_cast<std::uint64_t>(rvk_n));")
        out.append("        for (std::size_t rvk_i = 0; rvk_i < rvk_n; ++rvk_i) {")
        out.append(f"            const auto* rvk_s = {name}[rvk_i];")
        if p.has_lengths:
            # glShaderSource: a negative length, or none at all, means
            # the string is terminated rather than counted.
            out.append("            const std::size_t rvk_len = rvk_s == nullptr ? 0")
            out.append("                : (length != nullptr && length[rvk_i] >= 0)")
            out.append("                    ? static_cast<std::size_t>(length[rvk_i])")
            out.append("                    : std::strlen(reinterpret_cast<const char*>(rvk_s));")
        else:
            out.append("            const std::size_t rvk_len = rvk_s == nullptr ? 0")
            out.append("                : std::strlen(reinterpret_cast<const char*>(rvk_s));")
        out.append("            rvk_b.write_varint(static_cast<std::uint64_t>(rvk_len));")
        out.append("            if (rvk_len != 0) rvk_b.write(rvk_s, rvk_len);")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.ARRAY_IN:
        out.append(f"    std::size_t {name}_want = 0;")
        out.append(f"    if ({name} != nullptr) {name}_want = {_bytes_expr(p)};")
        _lease_for_write(name, out, guard=f"{name} != nullptr")
        out.append(f"    rvk_b.write_pod<std::uint8_t>("
                   f"{name} == nullptr ? 0 : ({name}_via_blob ? 3 : 1));")
        out.append(f"    if ({name}_via_blob) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_lease.offset));")
        out.append(f"    }} else if ({name} != nullptr) {{")
        out.append(f"        rvk_b.write_varint(static_cast<std::uint64_t>({name}_want));")
        out.append(f"        if ({name}_want != 0) rvk_b.write({name}, {name}_want);")
        out.append("    }")
        return
    if p.role in (Role.ARRAY_OUT, Role.STRING_OUT):
        out.append(f"    rvk_b.write_pod<std::uint8_t>({name} != nullptr ? 1 : 0);")
        out.append(f"    if ({name} != nullptr) {{")
        out.append(f"        const std::size_t rvk_bytes = {_bytes_expr(p)};")
        out.append("        rvk_b.write_varint(static_cast<std::uint64_t>(rvk_bytes));")
        out.append("    }")
        return
    raise AssertionError(f"no encoder for {p.role}")


def _decode_reply(cmd: Command, out: list[str]) -> None:
    kind = _ret_kind(cmd)
    fail = {"void": "return;", "scalar": "return 0;", "sync": "return 0;",
            "string": "return false;", "pointer": "return nullptr;"}[kind]
    if kind == "scalar":
        out.append("    std::uint64_t rvk_ret = 0;")
        out.append(f"    if (!rvk_r.read_varint(rvk_ret)) {fail}")
    elif kind == "sync":
        out.append("    std::uint64_t rvk_ret = 0;")
        out.append(f"    if (!rvk_r.read_pod(rvk_ret)) {fail}")
    elif kind == "string":
        out.append("    std::uint64_t rvk_present = 0;")
        out.append(f"    if (!rvk_r.read_varint(rvk_present)) {fail}")
        out.append("    std::uint64_t length = 0;")
        out.append(f"    if (!rvk_r.read_varint(length)) {fail}")
        out.append("    std::span<const std::uint8_t> rvk_text{};")
        out.append(f"    if (!rvk_r.read_view(static_cast<std::size_t>(length), rvk_text)) {fail}")
        out.append("    if (out != nullptr) {")
        out.append("        out->assign(reinterpret_cast<const char*>(rvk_text.data()), rvk_text.size());")
        out.append("    }")
    for p in cmd.params:
        if p.role in (Role.ARRAY_OUT, Role.STRING_OUT):
            out.append(f"    if ({p.name} != nullptr) {{")
            out.append("        std::uint64_t rvk_bytes = 0;")
            out.append(f"        if (!rvk_r.read_varint(rvk_bytes)) {fail}")
            out.append("        if (rvk_bytes != 0) {")
            out.append("            std::span<const std::uint8_t> rvk_src{};")
            out.append(f"            if (!rvk_r.read_view(static_cast<std::size_t>(rvk_bytes), rvk_src)) {fail}")
            out.append(f"            std::memcpy({p.name}, rvk_src.data(), rvk_src.size());")
            out.append("        }")
            out.append("    }")
        elif p.role is Role.PIXELS_OUT:
            # Through the blob the pixels are already here: the host
            # wrote them into memory this side lent it, so all that is
            # left is to hand them to the caller and give the lease
            # back.
            out.append(f"    if ({p.name}_via_blob) {{")
            out.append(f"        std::memcpy({p.name}, {p.name}_lease.data, {p.name}_want);")
            out.append("        ::rvk::client::BlobArena::for_transport(rvk_t)")
            out.append(f"            .give_back({p.name}_lease);")
            out.append("    }")
            # A read into a pixel buffer lands on the host and stays
            # there; nothing comes back for the caller to be given.
            out.append(f"    if ({p.name} != nullptr && !{p.name}_is_offset && "
                       f"!{p.name}_via_blob) {{")
            out.append("        std::uint64_t rvk_bytes = 0;")
            out.append(f"        if (!rvk_r.read_varint(rvk_bytes)) {fail}")
            out.append("        if (rvk_bytes != 0) {")
            out.append("            std::span<const std::uint8_t> rvk_src{};")
            out.append(f"            if (!rvk_r.read_view(static_cast<std::size_t>(rvk_bytes), rvk_src)) {fail}")
            out.append(f"            std::memcpy({p.name}, rvk_src.data(), rvk_src.size());")
            out.append("        }")
            out.append("    }")
    if kind == "scalar":
        out.append(f"    return static_cast<{cmd.return_type.cpp()}>(rvk_ret);")
    elif kind == "sync":
        out.append("    return rvk_ret;")
    elif kind == "string":
        out.append("    return rvk_present != 0;")


def emit_client(reg: Registry, out_dir: Path) -> None:
    h = [HEADER, "#pragma once\n",
         "#include <cstddef>", "#include <cstdint>", "#include <span>",
         "#include <string>\n",
         '#include "rvk/protocol/transport.hpp"',
         '#include "gl_types.h"\n',
         "namespace av::glproto {\n"]
    c = [HEADER, '#include "gl_dispatch_client.h"\n',
         "#include <cstring>\n",
         '#include "proto/wire/wire_writer.hpp"',
         '#include "proto/wire/wire_reader.hpp"',
         '#include "rvk/client/stub_report.hpp"',
         '#include "gl_helpers.h"',
         '#include "gl_protocol_ids.h"',
         '#include "gl_sizes.h"',
         '#include "rvk/client/blob_arena.hpp"',
         '#include "rvk/instr/profiler_macros.hpp"',
         '#include "rvk/apis/opengl/sync_table.hpp"\n',
         "namespace av::glproto {\n",
         "// Below one page a blob lease costs more than the reply slot",
         "// it would replace: the allocator rounds to a page either way.",
         "inline constexpr std::size_t kPixelBlobFloor = 4096;\n"]
    for cmd in reg.commands.values():
        h.append(f"{_client_signature(cmd, defaults=True)};")
        if cmd.name in reg.answered_by_guest:
            # Declared and called like any other, defined by hand: the
            # answer is in the guest already and asking for it would be
            # the round trip this exists to remove. See
            # `answered_by_guest` in gl_profile.toml.
            continue
        c.append(f"{_client_signature(cmd)} {{")
        # A span per call on the guest side.
        #
        # Without it a guest's profile is its presents and its waits and
        # nothing in between — the whole reason a frame took what it
        # took is the calls the application made, and they were the one
        # thing the timeline could not show. The server has had spans
        # around its replay since the beginning; this is the other half
        # of the same picture, and the two line up because the trace
        # headers carry a measured clock offset.
        #
        # "gl:" so a guest-side call sorts next to its server-side twin
        # rather than being mistaken for it. Compiled out entirely
        # without the profiler, and one predictable branch with it.
        c.append(f'    RVK_PROF_SCOPE("gl:{cmd.name}");')
        c.append("    ::av::WireWriter rvk_b;")
        if cmd.mints_handle:
            # The handle the guest is about to answer with, written
            # first so the server binds it before it decodes anything
            # that could fail. See rvk/apis/opengl/sync_table.hpp for
            # why the guest gets to choose it at all.
            c.append("    const std::uint64_t rvk_token = "
                     "::av::glproto::mint_sync_token();")
            c.append("    rvk_b.write_pod<std::uint64_t>(rvk_token);")
        for p in cmd.params:
            _encode_param(cmd, p, c)
        # A buffer that dropped a write must not be sent.
        #
        # Buffer records a failed write rather than throwing — it sits
        # under noexcept generated code — and nothing read that flag.
        # What went out instead was a header saying "four thousand
        # bytes of pixels follow" with no pixels behind it, and the
        # server answered "undecodable command" and dropped the whole
        # thing. That is a tile of an image that silently never
        # arrived. Sending nothing is no better for the picture, but it
        # is honest, and it says so once.
        c.append("    if (!rvk_b.ok()) {")
        c.append(f'        ::rvk::client::payload_dropped("gl", "{cmd.name}",')
        c.append("                                       rvk_b.size());")
        _hand_back_leases(cmd, c, sent=False, indent="        ")
        c.append(f"        {'return;' if _ret_kind(cmd) == 'void' else fail_for(cmd)}")
        c.append("    }")
        if cmd.is_async:
            c.append(f"    (void)rvk_t.send_async(kCmd_{cmd.name}, rvk_b.bytes());")
            _hand_back_leases(cmd, c, sent=True)
            if cmd.mints_handle:
                c.append("    return rvk_token;")
            c.append("}")
        else:
            kind = _ret_kind(cmd)
            fail = fail_for(cmd)
            c.append("    ::av::WireWriter rvk_reply;")
            c.append(f"    const bool rvk_sent = rvk_t.send_sync(kCmd_{cmd.name}, rvk_b.bytes(), &rvk_reply) ==")
            c.append("        ::rvk::protocol::TransportResult::Ok;")
            _hand_back_leases(cmd, c, sent=False)
            c.append("    if (!rvk_sent) {")
            c.append(f"        {fail}")
            c.append("    }")
            c.append("    ::av::WireReader rvk_r{rvk_reply.bytes()};")
            _decode_reply(cmd, c)
            c.append("}")
        c.append("")
    h += ["", "}  // namespace av::glproto", ""]
    c += ["}  // namespace av::glproto", ""]
    (out_dir / "gl_dispatch_client.h").write_text("\n".join(h))
    (out_dir / "gl_dispatch_client.cpp").write_text("\n".join(c))


# ---------------------------------------------------------------------
# The host's side
# ---------------------------------------------------------------------

def _decode_param(p: Param, out: list[str]) -> None:
    name = p.name
    if p.role is Role.IGNORED:
        out.append(f"    {p.type.cpp()} {name} = nullptr;")
        return
    if p.role is Role.SCALAR:
        if _is_pod_scalar(p.type.base):
            out.append(f"    {p.type.base} {name}{{}};")
            out.append(f"    if (!rvk_r.read_pod({name})) return false;")
        else:
            out.append(f"    {p.type.cpp()} {name}{{}};")
            out.append("    { std::uint64_t rvk_v = 0; if (!rvk_r.read_varint(rvk_v)) return false;")
            out.append(f"      {name} = static_cast<{p.type.cpp()}>(rvk_v); }}")
        return
    if p.role is Role.SYNC:
        # The guest's token, not the host's pointer. The table says
        # which of the host's fences it stands for; an unknown token
        # resolves to null, which is what GL does with a handle that was
        # never a handle. See rvk/apis/opengl/sync_table.hpp.
        out.append(f"    std::uint64_t {name}_token = 0;")
        out.append(f"    if (!rvk_r.read_pod({name}_token)) return false;")
        out.append(f"    GLsync {name} = static_cast<GLsync>("
                   f"::av::glproto::sync_for({name}_token));")
        return
    if p.role is Role.OFFSET_ARRAY:
        out.append(f"    const void** {name} = nullptr;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_n = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_n)) return false;")
        out.append("            auto** rvk_offsets = rvk_arena.allocate<const void*>(static_cast<std::size_t>(rvk_n) + 1);")
        out.append("            if (rvk_offsets == nullptr) return false;")
        out.append("            for (std::uint64_t rvk_i = 0; rvk_i < rvk_n; ++rvk_i) {")
        out.append("                std::uint64_t rvk_v = 0;")
        out.append("                if (!rvk_r.read_pod(rvk_v)) return false;")
        out.append("                rvk_offsets[rvk_i] = reinterpret_cast<const void*>(static_cast<std::uintptr_t>(rvk_v));")
        out.append("            }")
        out.append(f"            {name} = rvk_offsets;")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.BUFFER_OFFSET:
        out.append(f"    const void* {name} = nullptr;")
        out.append("    { std::uint64_t rvk_v = 0; if (!rvk_r.read_pod(rvk_v)) return false;")
        out.append(f"      {name} = reinterpret_cast<const void*>(static_cast<std::uintptr_t>(rvk_v)); }}")
        return
    if p.role is Role.PIXELS_IN:
        out.append(f"    const void* {name} = nullptr;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present == 2) {")
        out.append("            std::uint64_t rvk_offset = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_offset)) return false;")
        out.append(f"            {name} = reinterpret_cast<const void*>("
                   "static_cast<std::uintptr_t>(rvk_offset));")
        out.append("        } else if (rvk_present == 3) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            std::uint64_t rvk_at = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append("            if (!rvk_r.read_varint(rvk_at)) return false;")
        out.append("            if (rvk_gl.rvk_blob == nullptr) return false;")
        out.append(f"            {name} = rvk_gl.rvk_blob(rvk_gl.rvk_blob_user, rvk_at, rvk_bytes);")
        out.append(f"            if ({name} == nullptr) return false;")
        out.append("        } else if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append("            std::span<const std::uint8_t> rvk_view{};")
        out.append("            if (!rvk_r.read_view(static_cast<std::size_t>(rvk_bytes), rvk_view)) return false;")
        out.append(f"            {name} = rvk_view.data();")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.PIXELS_OUT:
        # Off the heap rather than out of the arena. A frame or a
        # texture level is larger than a thread's arena slice, and an
        # allocation that fails here is a command silently dropped —
        # which is what an eight-megabyte read looked like before.
        out.append(f"    std::vector<std::uint8_t> {name}_storage;")
        out.append(f"    void* {name} = nullptr;")
        out.append(f"    std::size_t {name}_bytes = 0;")
        out.append(f"    bool {name}_is_offset = false;")
        out.append(f"    bool {name}_via_blob = false;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present == 2) {")
        out.append("            std::uint64_t rvk_offset = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_offset)) return false;")
        out.append(f"            {name} = reinterpret_cast<void*>("
                   "static_cast<std::uintptr_t>(rvk_offset));")
        out.append(f"            {name}_is_offset = true;")
        out.append("        } else if (rvk_present == 3) {")
        # The guest lent a range of the region; GL writes into it
        # directly and nothing goes back through the reply.
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            std::uint64_t rvk_at = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append("            if (!rvk_r.read_varint(rvk_at)) return false;")
        out.append("            if (rvk_gl.rvk_blob == nullptr) return false;")
        # Bounds-checked against the whole mapping by the resolver,
        # which is the server's only defence against a guest that lies
        # about where its memory is.
        out.append(f"            {name} = rvk_gl.rvk_blob("
                   "rvk_gl.rvk_blob_user, rvk_at, rvk_bytes);")
        out.append(f"            if ({name} == nullptr) return false;")
        out.append(f"            {name}_bytes = static_cast<std::size_t>(rvk_bytes);")
        out.append(f"            {name}_via_blob = true;")
        out.append("        } else if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append(f"            {name}_bytes = static_cast<std::size_t>(rvk_bytes);")
        out.append(f"            {name}_storage.assign({name}_bytes + 1, 0);")
        out.append(f"            {name} = {name}_storage.data();")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.STRING_IN:
        out.append(f"    const {p.type.base}* {name} = nullptr;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_n = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_n)) return false;")
        out.append(f"            auto* rvk_text = rvk_arena.allocate<{p.type.base}>(static_cast<std::size_t>(rvk_n) + 1);")
        out.append("            if (rvk_text == nullptr) return false;")
        out.append("            std::span<const std::uint8_t> rvk_src{};")
        out.append("            if (!rvk_r.read_view(static_cast<std::size_t>(rvk_n), rvk_src)) return false;")
        out.append("            if (rvk_n != 0) std::memcpy(rvk_text, rvk_src.data(), rvk_src.size());")
        out.append("            rvk_text[rvk_n] = 0;")
        out.append(f"            {name} = rvk_text;")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.STRING_ARRAY_IN:
        base = p.type.base
        out.append(f"    const {base}** {name} = nullptr;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_n = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_n)) return false;")
        out.append(f"            auto** rvk_strings = rvk_arena.allocate<{base}*>(static_cast<std::size_t>(rvk_n) + 1);")
        out.append("            if (rvk_strings == nullptr) return false;")
        out.append("            for (std::uint64_t rvk_i = 0; rvk_i < rvk_n; ++rvk_i) {")
        out.append("                std::uint64_t rvk_len = 0;")
        out.append("                if (!rvk_r.read_varint(rvk_len)) return false;")
        out.append(f"                auto* rvk_text = rvk_arena.allocate<{base}>(static_cast<std::size_t>(rvk_len) + 1);")
        out.append("                if (rvk_text == nullptr) return false;")
        out.append("                std::span<const std::uint8_t> rvk_src{};")
        out.append("                if (!rvk_r.read_view(static_cast<std::size_t>(rvk_len), rvk_src)) return false;")
        out.append("                if (rvk_len != 0) std::memcpy(rvk_text, rvk_src.data(), rvk_src.size());")
        out.append("                rvk_text[rvk_len] = 0;")
        out.append("                rvk_strings[rvk_i] = rvk_text;")
        out.append("            }")
        out.append(f"            {name} = const_cast<const {base}**>(rvk_strings);")
        out.append("        }")
        out.append("    }")
        return
    if p.role is Role.ARRAY_IN:
        out.append(f"    const {p.type.base}* {name} = nullptr;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present == 3) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            std::uint64_t rvk_at = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append("            if (!rvk_r.read_varint(rvk_at)) return false;")
        out.append("            if (rvk_gl.rvk_blob == nullptr) return false;")
        out.append("            const void* rvk_from ="
                   " rvk_gl.rvk_blob(rvk_gl.rvk_blob_user, rvk_at, rvk_bytes);")
        out.append("            if (rvk_from == nullptr) return false;")
        out.append(f"            {name} = reinterpret_cast<const {p.type.base}*>(rvk_from);")
        out.append("        } else if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append("            std::span<const std::uint8_t> rvk_view{};")
        out.append("            if (!rvk_r.read_view(static_cast<std::size_t>(rvk_bytes), rvk_view)) return false;")
        out.append(f"            {name} = reinterpret_cast<const {p.type.base}*>(rvk_view.data());")
        out.append("        }")
        out.append("    }")
        return
    if p.role in (Role.ARRAY_OUT, Role.STRING_OUT):
        # Off the heap, for the reason above: a buffer read of several
        # megabytes is an ordinary thing to ask for.
        storage = "std::uint8_t" if p.type.base == "void" else p.type.base
        out.append(f"    std::vector<std::uint8_t> {name}_storage;")
        out.append(f"    {p.type.base}* {name} = nullptr;")
        out.append(f"    std::size_t {name}_bytes = 0;")
        out.append("    {")
        out.append("        std::uint8_t rvk_present = 0;")
        out.append("        if (!rvk_r.read_pod(rvk_present)) return false;")
        out.append("        if (rvk_present != 0) {")
        out.append("            std::uint64_t rvk_bytes = 0;")
        out.append("            if (!rvk_r.read_varint(rvk_bytes)) return false;")
        out.append(f"            {name}_bytes = static_cast<std::size_t>(rvk_bytes);")
        if p.length is not None and p.length.kind is LengthKind.PNAME:
            # A state query's length comes from a table of how many
            # values each enum answers with, and a table can be short:
            # GL_MODELVIEW_MATRIX is sixteen floats and was one, and
            # the host wrote all sixteen into a buffer sized for one.
            # That is heap corruption in the server, from a missing
            # line in a profile — so the buffer a query writes into is
            # always big enough for the largest answer GL has, and only
            # what was asked for is sent back. See kQuerySlack.
            out.append(f"            {name}_storage.assign("
                       f"std::max<std::size_t>({name}_bytes, "
                       f"kQuerySlack * sizeof({storage})) + sizeof({storage}), 0);")
        else:
            out.append(f"            {name}_storage.assign({name}_bytes + sizeof({storage}), 0);")
        out.append(f"            {name} = reinterpret_cast<{p.type.base}*>({name}_storage.data());")
        out.append("        }")
        out.append("    }")
        return
    raise AssertionError(f"no decoder for {p.role}")


def emit_server(reg: Registry, out_dir: Path) -> None:
    h = [HEADER, "#pragma once\n",
         "#include <cstdint>\n",
         '#include "proto/wire/wire_writer.hpp"',
         '#include "proto/wire/wire_reader.hpp"',
         '#include "gl_real_dispatch.h"\n',
         "namespace av::glproto {\n",
         "// Reads one command and calls the host's entry point for it.",
         "bool dispatch_command(const RealGl& gl, std::uint32_t cmd_id,",
         "                      ::av::WireReader& reader,",
         "                      ::av::WireWriter& reply) noexcept;\n",
         "}  // namespace av::glproto", ""]
    c = [HEADER, '#include "gl_dispatch_server.h"\n',
         "#include <algorithm>", "#include <cstring>", "#include <span>",
         "#include <vector>\n",
         '#include "proto/wire/wire_arena.hpp"',
         '#include "gl_protocol_ids.h"',
         '#include "gl_sizes.h"',
         '#include "rvk/instr/profiler_macros.hpp"',
         '#include "rvk/apis/opengl/sync_table.hpp"\n',
         "namespace av::glproto {\n",
         "// How many values the largest state query GL has answers",
         "// with: a four-by-four matrix, and room to spare. A query's",
         "// buffer is never smaller than this, whatever the guest asked",
         "// for, because the host writes as many values as the enum",
         "// really has and a short buffer is a heap the server owns.",
         "static constexpr std::size_t kQuerySlack = 32;\n"]
    for cmd in reg.commands.values():
        c.append(f"static bool decode_{cmd.name}(const RealGl& rvk_gl, "
                 "::av::WireReader& rvk_r, "
                 "::av::WireWriter& rvk_reply) {")
        # A span per call on the host side, matching the "drv:" the
        # Vulkan real-dispatch has always used.
        #
        # The server had `gl.replay` around a whole batch and nothing
        # inside it, so a profile could say the host spent four
        # milliseconds replaying and not which call it was in. With the
        # guest's "gl:" span and this one, the same command is visible
        # on both sides of the wire and the difference between them is
        # what the wire cost.
        #
        # It covers unpacking the arguments as well as making the call,
        # which is the whole of what the server spends on one command
        # and is the number worth having. Splitting the two would need a
        # span around each of the four shapes the call site takes — void,
        # a value, a string, a pointer — to separate a decode that is
        # tens of nanoseconds from a driver call that is not.
        c.append(f'    RVK_PROF_SCOPE("drv:{cmd.name}");')
        c.append("    ::av::WireArena rvk_arena;")
        c.append("    (void)rvk_arena; (void)rvk_reply;")
        if cmd.mints_handle:
            c.append("    std::uint64_t rvk_token = 0;")
            c.append("    if (!rvk_r.read_pod(rvk_token)) return false;")
        for p in cmd.params:
            _decode_param(p, c)
        # A pixel parameter is decoded as void*, which is what every
        # pixel transfer's own signature says. A query result is not:
        # glGetQueryObjectuiv wants GLuint*, and it is carried the same
        # way because the question — is this an address or an offset
        # into a bound buffer — is the same one.
        call_args = ", ".join(
            (f"static_cast<{p.type.cpp()}>({p.name})"
             if p.role is Role.PIXELS_OUT and p.type.base != "void"
             else p.name)
            for p in cmd.params)
        c.append(f"    if (rvk_gl.{cmd.name} == nullptr) return false;")
        kind = _ret_kind(cmd)
        if kind == "void":
            c.append(f"    rvk_gl.{cmd.name}({call_args});")
        else:
            c.append(f"    const auto rvk_ret = rvk_gl.{cmd.name}({call_args});")
        if cmd.mints_handle:
            # The guest already answered with the token; all that is
            # owed here is the note of which fence it meant.
            c.append("    ::av::glproto::bind_sync(rvk_token, rvk_ret);")
        if kind == "scalar":
            c.append("    rvk_reply.write_varint(static_cast<std::uint64_t>(rvk_ret));")
        elif kind == "sync" and not cmd.mints_handle:
            c.append("    rvk_reply.write_pod<std::uint64_t>(")
            c.append("        static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(rvk_ret)));")
        elif kind == "string":
            c.append("    const auto* rvk_text = reinterpret_cast<const char*>(rvk_ret);")
            c.append("    rvk_reply.write_varint(rvk_text != nullptr ? 1 : 0);")
            c.append("    const std::size_t rvk_length = rvk_text != nullptr ? std::strlen(rvk_text) : 0;")
            c.append("    rvk_reply.write_varint(static_cast<std::uint64_t>(rvk_length));")
            c.append("    if (rvk_length != 0) rvk_reply.write(rvk_text, rvk_length);")
        elif kind == "pointer":
            c.append("    rvk_reply.write_pod<std::uint64_t>(")
            c.append("        static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(rvk_ret)));")
        for p in cmd.params:
            if p.role in (Role.ARRAY_OUT, Role.STRING_OUT, Role.PIXELS_OUT):
                guard = (f"{p.name} != nullptr && !{p.name}_is_offset"
                         f" && !{p.name}_via_blob"
                         if p.role is Role.PIXELS_OUT else f"{p.name} != nullptr")
                c.append(f"    if ({guard}) {{")
                c.append(f"        rvk_reply.write_varint(static_cast<std::uint64_t>({p.name}_bytes));")
                c.append(f"        if ({p.name}_bytes != 0) rvk_reply.write({p.name}, {p.name}_bytes);")
                c.append("    }")
        if cmd.name == "glDeleteSync":
            # The host's object is gone; without this the table keeps a
            # dead entry per fence, and a game makes one a frame.
            c.append("    ::av::glproto::forget_sync(sync_token);")
        c.append("    return true;")
        c.append("}")
        c.append("")
    c.append("bool dispatch_command(const RealGl& rvk_gl, std::uint32_t cmd_id,")
    c.append("                      ::av::WireReader& rvk_r,")
    c.append("                      ::av::WireWriter& rvk_reply) noexcept {")
    c.append("    switch (cmd_id) {")
    for cmd in reg.commands.values():
        c.append(f"        case kCmd_{cmd.name}: return decode_{cmd.name}(rvk_gl, rvk_r, rvk_reply);")
    c += ["        default: return false;", "    }", "}", "",
          "}  // namespace av::glproto", ""]
    (out_dir / "gl_dispatch_server.h").write_text("\n".join(h))
    (out_dir / "gl_dispatch_server.cpp").write_text("\n".join(c))


