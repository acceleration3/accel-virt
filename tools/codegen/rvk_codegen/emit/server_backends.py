"""Generate concrete ``ServerDispatch`` subclasses.

The abstract ``ServerDispatch`` is generated by ``emit/dispatch.py``. Two
concrete subclasses ride on top of it and are also generated:

  * ``DefaultServerDispatch`` — every method overridden with a no-op
    default. ``VkResult``-returning methods return ``VK_SUCCESS``; count
    outputs of two-call enumerations are zeroed so callers don't see
    stale memory. Subclasses (StubDispatch, test fixtures, etc.) can now
    inherit from this and override only the methods they care about,
    instead of having to maintain a no-op stub for every newly-added
    command.

  * ``RealVulkanDispatch`` — every method forwards directly into the host
    Vulkan loader (``::vkXxx``). The only transformation is that
    ``VkAllocationCallbacks`` parameters are always replaced with
    ``nullptr`` (the RVK protocol does not forward the client's
    allocator). This was previously hand-written; now it's a one-line
    pass-through per command, generated.
"""

from __future__ import annotations

import re

from pathlib import Path

from ..ir import Command, Param, Registry
from .common import GENERATED_BANNER, header_guard, write


def _param_cpp(t) -> str:
    """Decay fixed-array params to pointers (C function-signature semantics)."""
    s = t.base
    eff_ptr = t.pointer_depth + (1 if t.fixed_dim is not None else 0)
    if eff_ptr:
        s += "*" * eff_ptr
    if t.is_const:
        s = "const " + s
    return s


def _signature(cmd: Command, body: str = "") -> str:
    """The override's signature, naming only the parameters the body uses.

    A parameter a body never touches is `-Wunused-parameter` under this
    repository's warning set, and these bodies genuinely do not touch some of
    them: the allocator is replaced with nullptr on every call, because the
    protocol does not forward the client's allocator. Passing the body in and
    dropping the unused names is the emitter's job rather than the reader's.
    """
    parts = []
    for p in cmd.params:
        used = body and re.search(r"\b" + re.escape(p.name) + r"\b", body) is not None
        parts.append(f"{_param_cpp(p.type)} {p.name}" if used else f"{_param_cpp(p.type)}")
    return f"{cmd.return_type.cpp()} on_{cmd.name}({', '.join(parts)})"


def _is_count_param(cmd: Command, idx: int) -> bool:
    """True if ``cmd.params[idx]`` is the count side of a count/array pair."""
    if idx + 1 >= len(cmd.params):
        return False
    a, b = cmd.params[idx], cmd.params[idx + 1]
    if a.type.base not in ("uint32_t", "size_t"):
        return False
    if a.type.pointer_depth != 1 or b.type.pointer_depth != 1:
        return False
    return b.len_expr == a.name


def _default_body(cmd: Command) -> list[str]:
    """No-op default body: zero count outputs, return VK_SUCCESS if non-void."""
    body: list[str] = []
    for i, p in enumerate(cmd.params):
        if _is_count_param(cmd, i):
            body.append(
                f"        if ({p.name} != nullptr) {{ *{p.name} = 0; }}"
            )
    if cmd.return_type.base != "void":
        body.append("        return VK_SUCCESS;")
    return body


def _emit_default(reg: Registry) -> str:
    lines: list[str] = [
        GENERATED_BANNER,
        "",
        "#include <cstdint>",
        "",
        "#include <vulkan/vulkan_core.h>",
        "",
        '#include "vk_dispatch_server.h"',
        "",
        "namespace av::vkproto {",
        "",
        "// Concrete ServerDispatch with a no-op default for every command.",
        "// Subclasses override only the methods they care about; new commands",
        "// added to the codegen profile inherit a sane default automatically.",
        "class DefaultServerDispatch : public ServerDispatch {",
        "public:",
    ]
    for cmd in sorted(reg.commands.values(), key=lambda c: c.cmd_id):
        body = _default_body(cmd)
        if not body:
            lines.append(f"    {_signature(cmd)} override {{}}")
        else:
            lines.append(f"    {_signature(cmd, chr(10).join(body))} override {{")
            lines.extend(body)
            lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace av::vkproto")
    lines.append("")
    return "\n".join(lines[1:])


def _real_call_args(cmd: Command) -> list[str]:
    """Argument list for the real ::vkXxx call: same names, but nullptr for allocator."""
    out: list[str] = []
    for p in cmd.params:
        if p.type.base == "VkAllocationCallbacks":
            out.append("nullptr")
        else:
            out.append(p.name)
    return out


def _emit_real(reg: Registry) -> str:
    lines: list[str] = [
        GENERATED_BANNER,
        "",
        "#include <cstdint>",
        "",
        "#include <vulkan/vulkan_core.h>",
        "",
        '#include "vk_dispatch_server.h"',
        "",
        "namespace av::vkproto {",
        "",
        "// Concrete ServerDispatch that forwards every command into the host",
        "// Vulkan loader. Use this when the server should drive a real GPU.",
        "// VkAllocationCallbacks parameters are always replaced with nullptr",
        "// — the RVK protocol does not forward the client's allocator.",
        "class RealVulkanDispatch : public ServerDispatch {",
        "public:",
    ]
    members: list[str] = []
    for cmd in sorted(reg.commands.values(), key=lambda c: c.cmd_id):
        args = ", ".join(_real_call_args(cmd))
        sig = _signature(cmd, args)

        if cmd.name == "vkCreateInstance":
            # Capture the instance: every extension entry point below is
            # resolved through it, and there is no other point in the
            # generated dispatch where it is available.
            lines.extend([
                f"    {sig} override {{",
                f"        const VkResult rc = ::vkCreateInstance({args});",
                "        if (rc == VK_SUCCESS && pInstance != nullptr) "
                "{ instance_ = *pInstance; }",
                "        return rc;",
                "    }",
            ])
            continue

        if not cmd.extension_only:
            # Alias spellings (vkFooKHR promoted to vkFoo) are not exported
            # by the loader; only the core symbol is. Calling cmd.name here
            # links fine for everything else and fails for exactly those.
            call = f"::{cmd.alias_of or cmd.name}({args})"
            if cmd.return_type.base == "void":
                lines.extend([f"    {sig} override {{", f"        {call};", "    }"])
            else:
                lines.extend([f"    {sig} override {{", f"        return {call};", "    }"])
            continue

        # Extension-only: the loader exports no symbol, so linking
        # against it fails outright. Resolve through the instance the
        # first time it is called and cache it. vkGetInstanceProcAddr
        # answers for device-level commands too — it hands back a
        # trampoline — which avoids having to map a command buffer or
        # queue back to the device that owns it.
        pfn = f"pfn_{cmd.name}_"
        members.append(f"    PFN_{cmd.name} {pfn} = nullptr;")
        body = [
            f"    {sig} override {{",
            f"        if ({pfn} == nullptr) {{",
            f"            {pfn} = reinterpret_cast<PFN_{cmd.name}>("
            f'::vkGetInstanceProcAddr(instance_, "{cmd.name}"));',
            "        }",
            f"        if ({pfn} == nullptr) {{",
        ]
        if cmd.return_type.base == "void":
            body.append("            return;")
            body.append("        }")
            body.append(f"        {pfn}({args});")
        elif cmd.return_type.base == "VkResult":
            body.append("            return VK_ERROR_EXTENSION_NOT_PRESENT;")
            body.append("        }")
            body.append(f"        return {pfn}({args});")
        else:
            body.append(f"            return {cmd.return_type.cpp()}{{}};")
            body.append("        }")
            body.append(f"        return {pfn}({args});")
        body.append("    }")
        lines.extend(body)

    lines.append("")
    lines.append("private:")
    # Captured in on_vkCreateInstance below; every proc-addr lookup goes
    # through it.
    lines.append("    VkInstance instance_ = VK_NULL_HANDLE;")
    lines.extend(members)
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace av::vkproto")
    lines.append("")
    return "\n".join(lines[1:])


def emit(reg: Registry, out_dir: Path) -> None:
    write(out_dir / "vk_default_dispatch.h", header_guard(_emit_default(reg)))
    write(out_dir / "vk_real_dispatch.h", header_guard(_emit_real(reg)))
