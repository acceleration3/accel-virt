# How each table's slots find the object that answers them from their first
# parameter, and the class that is.
TABLES = [
    (DEVICE_TABLE, "D3D12DDI_HDEVICE", "d3d12", "D3d12DeviceHandle({h}.pDrvPrivate).device()", "device"),
    (QUEUE_TABLE, "D3D12DDI_HCOMMANDQUEUE", "d3d12q", "D3d12RecordHandle({h}.pDrvPrivate).device()", "device"),
    (EXTENDED_TABLE, "D3D12DDI_HDEVICE", "d3d12x", "D3d12DeviceHandle({h}.pDrvPrivate).device()", "device"),
    (LIST_TABLE, "D3D12DDI_HCOMMANDLIST", "d3d12l", "D3d12RecordHandle({h}.pDrvPrivate).recorder()", "recorder"),
]

FILLERS = {DEVICE_TABLE: "fill_device_funcs12", QUEUE_TABLE: "fill_queue_funcs12", LIST_TABLE: "fill_list_funcs12",
           EXTENDED_TABLE: "fill_extended_funcs12"}

# What an unimplemented slot answers, by its return type.
DEFAULTS = {"HRESULT": "E_NOTIMPL", "void": None}


def dump():
    with tempfile.TemporaryDirectory() as scratch:
        source = pathlib.Path(scratch) / "probe.cpp"
        source.write_text(PROBE)
        command = ["clang-cl", "/GR-", "/EHs-c-", "/Zl", "/X", "/D_AMD64_", "/DAMD64", "/D_WIN64",
                   "/DWIN32_LEAN_AND_MEAN", "/DNOMINMAX", f"/clang:-ivfsoverlay{KIT}/overlay.yaml",
                   "-imsvc/windows-kit/km/crt", "-imsvc/windows-kit/um", "-imsvc/windows-kit/sdk-shared",
                   "-imsvc/windows-kit/wdk-shared", "-clang:-std=c++23", "--target=x86_64-pc-windows-msvc", "/Zs",
                   "-Xclang", "-ast-dump=json", "-Xclang", "-ast-dump-filter=_FUNCS_", str(source)]
        text = subprocess.run(command, capture_output=True, text=True, check=True).stdout
    decoder = json.JSONDecoder()
    at = 0
    found = {}
    while at < len(text):
        while at < len(text) and text[at].isspace():
            at += 1
        if at >= len(text):
            break
        node, at = decoder.raw_decode(text, at)
        name = node.get("name")
        if node.get("kind") == "CXXRecordDecl" and node.get("completeDefinition") and name in IMPLEMENTED:
            found[name] = [field for field in node["inner"] if field["kind"] == "FieldDecl"]
    missing = [name for name in IMPLEMENTED if name not in found]
    if missing:
        raise SystemExit(f"clang reported no definition of {missing}")
    return found


def split_top(parameters):
    depth, current, out = 0, "", []
    for ch in parameters:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


SIGNATURE = re.compile(r"^(?P<ret>.+?) ?\(\*\)\((?P<params>.*)\)$")


def snake(name):
    name = name[len("pfn"):]
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()
    return name.replace("_i_a_", "_ia_").replace("_o_m_", "_om_").replace("_s_o_", "_so_")


def entries(fields):
    out = []
    for field in fields:
        qual = field["type"].get("desugaredQualType", field["type"]["qualType"])
        qual = qual.replace(" __attribute__((stdcall))", "")
        matched = SIGNATURE.match(qual)
        if not matched:
            out.append((field["name"], None, None))
            continue
        out.append((field["name"], matched["ret"], split_top(matched["params"])))
    return out


def ret_type(ret):
    return {"void": "VOID", "int": "BOOL"}.get(ret, ret)


def default_return(ret):
    if ret in DEFAULTS:
        return DEFAULTS[ret]
    if ret.endswith("*"):
        return "nullptr"
    return f"{ret_type(ret)}{{}}"


def thunks(tables):
    lines = [HEADER, "/* The ABI boundary C requires: the runtime calls each slot with the handle it",
             " * was given and nothing else, so each thunk is one line into the object the",
             " * handle's block names, or the answer a driver without the slot's feature",
             " * gives. */",
             '#include "core/trace/function_scope.hpp"', '#include "um/d3d/d3d12_ddi.hpp"',
             '#include "um/d3d/d3d12_device.hpp"', '#include "um/d3d/d3d12_device_handle.hpp"', '#include "um/d3d/d3d12_record_handle.hpp"',
             '#include "um/d3d/d3d12_recorder.hpp"', '#include "um/d3d/d3d12_tables.hpp"', "", "namespace av::d3d12 {", "", "namespace {", ""]
    fills = []
    for table, first, prefix, target, _owner in TABLES:
        fill = [f"void {FILLERS[table]}({table} &table)", "{", f'    AV_SCOPE("{FILLERS[table]}");']
        for name, ret, parameters in tables[table]:
            if ret is None:
                continue
            names = ["handle"] + [f"a{index}" for index in range(1, len(parameters))]
            declared = ", ".join(f"{kind} {label}" for kind, label in zip(parameters, names))
            arguments = ", ".join(names[1:])
            keyword = "" if ret == "void" else "return "
            symbol = f"rvkumd_{prefix}_{name[3:]}"
            lines.append(f"extern \"C\" {ret_type(ret)} APIENTRY {symbol}({declared})")
            owned = parameters[0] == first
            if name in IMPLEMENTED[table]:
                if not owned:
                    raise SystemExit(f"{name}: implemented, but its first parameter is {parameters[0]}")
                call_arguments = ", ".join(names) if table == LIST_TABLE or table == QUEUE_TABLE else arguments
                if table in (DEVICE_TABLE, EXTENDED_TABLE) and ret == "HRESULT":
                    # A refusal is logged with the slot's name: most say nothing of why, and the runtime
                    # hands the bare code to the application.
                    lines.append(f"{{ D3d12Device &device = {target.format(h='handle')}; "
                                 f"return device.answered(\"{name[3:]}\", device.{snake(name)}({call_arguments})); }}")
                else:
                    lines.append(f"{{ {keyword}{target.format(h='handle')}.{snake(name)}({call_arguments}); }}")
            else:
                answer = default_return(ret)
                unused = "".join(f" static_cast<void>({label});" for label in names)
                if owned and table == DEVICE_TABLE:
                    call = f"{target.format(h='handle')}.unsupported(\"{name}\");"
                    unused = "".join(f" static_cast<void>({label});" for label in names[1:])
                else:
                    call = ""
                tail = f" return {answer};" if answer is not None else ""
                lines.append(f"{{{unused} {call}{tail} }}".replace("  ", " "))
            lines.append("")
            fill.append(f"    table.{name} = &{symbol};")
        fill += ["}", ""]
        fills += fill
    lines += ["}  // namespace", ""] + fills + ["}  // namespace av::d3d12", ""]
    return "\n".join(lines)


def methods(tables, owner):
    lines = [HEADER]
    for table, _first, _prefix, _target, table_owner in TABLES:
        if table_owner != owner:
            continue
        lines.append(f"// {table}")
        for name, ret, parameters in tables[table]:
            if ret is None or name not in IMPLEMENTED[table]:
                continue
            own = parameters if table in (LIST_TABLE, QUEUE_TABLE) else parameters[1:]
            lines.append(f"{ret_type(ret)} {snake(name)}({', '.join(own)});")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--list", action="store_true", help="print every slot's signature")
    args = parser.parse_args()
    tables = {name: entries(fields) for name, fields in dump().items()}
    if args.list:
        for table, _first, _prefix, _target, _owner in TABLES:
            print(f"== {table}")
            for name, ret, parameters in tables[table]:
                mark = "*" if name in IMPLEMENTED[table] else " "
                print(f"{mark} {name}: {ret} ({', '.join(parameters or [])})")
        return 0
    files = {"d3d12_thunks.cpp": thunks(tables), "d3d12_device_ddi.inc": methods(tables, "device"),
             "d3d12_recorder_ddi.inc": methods(tables, "recorder")}
    if args.check:
        differ = [name for name, text in files.items()
                  if not (OUT / name).exists() or (OUT / name).read_text() != text]
        for name in differ:
            print(f"generated: {name} differs from what tools/gen_d3d12_ddi.py writes", file=sys.stderr)
        return 1 if differ else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"gen_d3d12_ddi: {sum(len(t) for t in tables.values())} slots -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
