#!/usr/bin/env python3
"""The Direct3D 11 device-function table's thunks, from the WDK's own header.

The table the runtime hands a user-mode driver at WDDM 3.2's interface is
D3DWDDM2_6DDI_DEVICEFUNCS: 176 function pointers, each typed by a PFN typedef
that is itself one of several versions of the same DDI. Writing 176 thunks by
hand is 176 chances to get a signature subtly wrong, and a wrong signature is a
stack the runtime and the driver disagree about. So clang reads the kit's
header for the Windows target, and this writes, from the types it reports:

  src/um/d3d/generated/d3d11_device_thunks.cpp   one ABI thunk per slot, each one
                                                  line into D3d11Device, and the
                                                  function that fills the table
  src/um/d3d/generated/d3d11_device_ddi.inc       the D3d11Device methods they
                                                  call, included in its class

    tools/gen_d3d11_ddi.py            # regenerate
    tools/gen_d3d11_ddi.py --check    # fail if the committed files differ
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "um" / "d3d" / "generated"
KIT = ROOT / "third_party" / "windows-kit"
TABLE = "D3DWDDM2_6DDI_DEVICEFUNCS"

PROBE = """#include <windows.h>
typedef _Return_type_success_(return >= 0) LONG NTSTATUS;
#include <d3d10umddi.h>
D3DWDDM2_6DDI_DEVICEFUNCS *probe;
"""

HEADER = "// THIS FILE IS GENERATED BY tools/gen_d3d11_ddi.py FROM THE WDK'S d3d10umddi.h. DO NOT EDIT.\n"


def dump():
    with tempfile.TemporaryDirectory() as scratch:
        source = pathlib.Path(scratch) / "probe.cpp"
        source.write_text(PROBE)
        command = ["clang-cl", "/GR-", "/EHs-c-", "/Zl", "/X", "/D_AMD64_", "/DAMD64", "/D_WIN64",
                   "/DWIN32_LEAN_AND_MEAN", "/DNOMINMAX", f"/clang:-ivfsoverlay{KIT}/overlay.yaml",
                   "-imsvc/windows-kit/km/crt", "-imsvc/windows-kit/um", "-imsvc/windows-kit/sdk-shared",
                   "-imsvc/windows-kit/wdk-shared", "-clang:-std=c++23", "--target=x86_64-pc-windows-msvc", "/Zs",
                   "-Xclang", "-ast-dump=json", "-Xclang", f"-ast-dump-filter={TABLE}", str(source)]
        text = subprocess.run(command, capture_output=True, text=True, check=True).stdout
    decoder = json.JSONDecoder()
    at = 0
    while at < len(text):
        while at < len(text) and text[at].isspace():
            at += 1
        if at >= len(text):
            break
        node, at = decoder.raw_decode(text, at)
        if node.get("kind") == "CXXRecordDecl" and node.get("completeDefinition") and node.get("name") == TABLE:
            return [field for field in node["inner"] if field["kind"] == "FieldDecl"]
    raise SystemExit(f"clang reported no definition of {TABLE}")


def split_top(parameters):
    depth, current, out = 0, "", []
    for ch in parameters:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


SIGNATURE = re.compile(r"^(?P<ret>.+?) \(\*\)\((?P<params>.*)\)$")


def snake(name):
    name = name[len("pfn"):]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def entries(fields):
    out = []
    for field in fields:
        signature = field["type"].get("desugaredQualType", field["type"]["qualType"])
        signature = signature.replace(" __attribute__((stdcall))", "")
        matched = SIGNATURE.match(signature)
        if not matched:
            raise SystemExit(f"{field['name']}: cannot read {signature!r}")
        parameters = split_top(matched["params"])
        if not parameters or parameters[0] != "D3D10DDI_HDEVICE":
            raise SystemExit(f"{field['name']}: first parameter is {parameters[:1]}, not the device")
        out.append((field["name"], field["type"]["qualType"], matched["ret"], parameters))
    return out


def ret_type(ret):
    return {"void": "VOID", "int": "BOOL"}.get(ret, ret)


def thunks(table):
    lines = [HEADER, "/* The ABI boundary C requires: the runtime calls each slot with the device", " * handle it was given and nothing else, so each thunk is one line into the", " * device the handle's block names. */",
             '#include "um/d3d/d3d11_ddi.hpp"', '#include "um/d3d/d3d11_device.hpp"', '#include "um/d3d/device_handle.hpp"', "", "namespace av::d3d11 {", "", "namespace {", ""]
    for name, _pfn, ret, parameters in table:
        names = ["device"] + [f"a{index}" for index in range(1, len(parameters))]
        declared = ", ".join(f"{kind} {label}" for kind, label in zip(parameters, names))
        arguments = ", ".join(names[1:])
        keyword = "" if ret == "void" else "return "
        lines.append(f"{ret_type(ret)} APIENTRY ddi_{name[3:]}({declared})")
        lines.append(f"{{ {keyword}DeviceHandle(device.pDrvPrivate).device().{snake(name)}({arguments}); }}")
        lines.append("")
    lines += ["}  // namespace", "", f"void fill_device_funcs({TABLE} &table)", "{"]
    for name, _pfn, _ret, _parameters in table:
        lines.append(f"    table.{name} = &ddi_{name[3:]};")
    lines += ["}", "", "}  // namespace av::d3d11", ""]
    return "\n".join(lines)


def methods(table):
    lines = [HEADER, "// Included inside class D3d11Device: one method per device-table slot.", ""]
    for name, _pfn, ret, parameters in table:
        declared = ", ".join(parameters[1:])
        lines.append(f"{ret_type(ret)} {snake(name)}({declared});")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table = entries(dump())
    files = {"d3d11_device_thunks.cpp": thunks(table), "d3d11_device_ddi.inc": methods(table)}
    if args.check:
        differ = [name for name, text in files.items()
                  if not (OUT / name).exists() or (OUT / name).read_text() != text]
        for name in differ:
            print(f"generated: {name} differs from what tools/gen_d3d11_ddi.py writes", file=sys.stderr)
        return 1 if differ else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"gen_d3d11_ddi: {len(table)} slots -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
