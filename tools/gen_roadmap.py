#!/usr/bin/env python3
"""Regenerate docs/roadmap.md from the feature table."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from features import FEATURES

LEVEL_TITLES = {
    "BASE": "WDDM 1.0 (Windows Vista)", "WIN7": "WDDM 1.1 (Windows 7)",
    "WIN8": "WDDM 1.2 (Windows 8)", "WDDM1_3": "WDDM 1.3 (Windows 8.1)",
    "WDDM2_0": "WDDM 2.0 (Windows 10 1507)", "WDDM2_1": "WDDM 2.1 (1607)",
    "WDDM2_2": "WDDM 2.2 (1703)", "WDDM2_3": "WDDM 2.3 (1709)",
    "WDDM2_4": "WDDM 2.4 (1803)", "WDDM2_5": "WDDM 2.5 (1809)",
    "WDDM2_6": "WDDM 2.6 (1903)", "WDDM2_7": "WDDM 2.7 (2004)",
    "WDDM2_8": "WDDM 2.8 (20H2)", "WDDM2_9": "WDDM 2.9 (21H2)",
    "WDDM3_0": "WDDM 3.0 (22H2)", "WDDM3_1": "WDDM 3.1 (23H2)",
    "WDDM3_2": "WDDM 3.2 (24H2)",
}


def load_table(root):
    rows = []
    for ln in open(os.path.join(root, "docs/ref/driver_init_table.md")):
        m = re.match(r"\| *(\d+) \| `([^`]+)` \| `([^`]+)` \| (\S+) \|", ln)
        if m:
            rows.append((int(m.group(1)), m.group(2), m.group(3), m.group(4)))
    return rows


def slots_for(feat, rows):
    _id, _short, level, _status, _title, _summary, extra = feat
    extra = extra or {}
    if extra.get("slots"):
        want = set(extra["slots"])
        return [r for r in rows if r[1] in want]
    levels = set(extra.get("merge", []))
    if level and level != "BASE+" and not levels:
        levels = {level}
    if not levels:
        return []
    # Reserved fields are padding in the table, not DDIs anyone implements.
    return [r for r in rows if r[3] in levels and not r[1].startswith("Reserved")]


rows = load_table(ROOT)
out = ["# Roadmap", "",
 "Generated by `tools/gen_roadmap.py` from `tools/features.py`.", "",
 "`implement` build and test it · `partial` only the listed subset · "
 "`stub` return the correct refusal, and test the refusal · "
 "`skip` leave the slot NULL", "",
 "| # | Feature | WDDM level | Status | DDI slots | Depends on |",
 "|---|---|---|---|--:|---|"]
for f in FEATURES:
    fid, _short, level, status, title, _s, extra = f
    extra = extra or {}
    n = len(slots_for(f, rows))
    lvl = LEVEL_TITLES.get(level, level or "—").split(" (")[0]
    deps = ", ".join(extra.get("deps", [])) or "—"
    out.append(f"| {fid} | {title} | {lvl} | "
               f"`{status}` | {n or '—'} | {deps} |")
total = sum(len(slots_for(f, rows)) for f in FEATURES if (f[6] or {}).get("slots")
            or f[2])
out += ["", f"{len(FEATURES)} features. The `DRIVER_INITIALIZATION_DATA` table has "
        f"193 fields at WDDM 3.2 (187 DDIs, 5 reserved); see `docs/ref/driver_init_table.md`.", ""]
open(os.path.join(ROOT, "docs/roadmap.md"), "w").write("\n".join(out))
print("wrote docs/roadmap.md")
