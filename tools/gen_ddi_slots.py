#!/usr/bin/env python3
"""Generate the DDI slot names and the compile-time proof that av::DdiTable is
laid out exactly like the WDK's DRIVER_INITIALIZATION_DATA.

Source of truth: docs/ref/driver_init_table.md, itself extracted from the WDK
headers by tools/re/ddi_extract.py.

  gen_ddi_slots.py [--root <repository root>] [--check]
"""
import argparse
import os
import re
import sys

ROW = re.compile(r"^\| *(\d+) \| `(\w+)` \| `([^`]+)` \|")
HEADER = "src/core/ddi_slot.hpp"
LAYOUT = "src/km/ddi_table_layout.cpp"


def slots(root):
    with open(os.path.join(root, "docs/ref/driver_init_table.md")) as table:
        return [(int(m.group(1)), m.group(2)) for m in map(ROW.match, table) if m]


def header_text(rows):
    lines = [
        "/* Generated by tools/gen_ddi_slots.py from docs/ref/driver_init_table.md - do not edit.",
        " *",
        " * One enumerator per field of DRIVER_INITIALIZATION_DATA at WDDM 3.2, valued at",
        " * its position. Enumerators keep the WDK field names, so a slot greps straight",
        " * to its header field. */",
        "#ifndef AV_DDI_SLOT_HPP",
        "#define AV_DDI_SLOT_HPP",
        "",
        "#include <stdint.h>",
        "",
        "namespace av {",
        "",
        "enum class DdiSlot : uint16_t {",
    ]
    lines += [f"    {name} = {index}," for index, name in rows]
    lines += ["};", "", "}  // namespace av", "", "#endif  // AV_DDI_SLOT_HPP", ""]
    return "\n".join(lines)


def layout_text(rows):
    lines = [
        "/* Generated by tools/gen_ddi_slots.py from docs/ref/driver_init_table.md - do not edit.",
        " *",
        " * Proves at compile time that av::DdiTable, which core fills and the harness",
        " * drives on Linux, is byte-for-byte the DRIVER_INITIALIZATION_DATA dxgkrnl reads. */",
        "#include <ntddk.h>",
        "#include <dispmprt.h>",
        "",
        "#include \"ddi_table.hpp\"",
        "",
        "static_assert(sizeof(av::DdiTable) == sizeof(DRIVER_INITIALIZATION_DATA),",
        "              \"DdiTable size differs from DRIVER_INITIALIZATION_DATA\");",
    ]
    for index, name in rows:
        if index == 0:
            continue
        lines += [
            f"static_assert(offsetof(DRIVER_INITIALIZATION_DATA, {name}) ==",
            f"                  av::DdiTable::first_routine_offset +",
            f"                  sizeof(void *) * (static_cast<size_t>(av::DdiSlot::{name}) - 1u),",
            f"              \"{name}\");",
        ]
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    rows = slots(args.root)
    outputs = {HEADER: header_text(rows), LAYOUT: layout_text(rows)}
    stale = []
    for relative, text in outputs.items():
        path = os.path.join(args.root, relative)
        current = open(path).read() if os.path.exists(path) else None
        if args.check:
            if current != text:
                stale.append(relative)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as out:
            out.write(text)
    for relative in stale:
        print(f"{relative}: stale; run tools/gen_ddi_slots.py", file=sys.stderr)
    if stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
