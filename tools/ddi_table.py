"""A Direct3D runtime's device-function table, read from the WDK's own header,
and the thunks and methods a user-mode driver fills it with.

The runtime hands a user-mode driver a table of function pointers, each typed
by a PFN typedef. Writing a hundred thunks by hand is a hundred chances to get
a signature subtly wrong, and a wrong signature is a stack the runtime and the
driver disagree about. So clang reads the kit's header for the Windows target,
and DdiTable writes, from the types it reports:

  <out>/<prefix>_device_thunks.cpp   one ABI thunk per slot, each one line into
                                     the device, and the function that fills
                                     the table
  <out>/<prefix>_device_ddi.inc      the device methods they call, included in
                                     its class

Direct3D 9's and 11's tables differ only in what DdiTable is told: the header,
the table, how a slot's first parameter names the device, which slots the root
answers and which stay empty (tools/gen_d3d9_ddi.py, tools/gen_d3d11_ddi.py).
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "um" / "d3d" / "generated"
KIT = ROOT / "third_party" / "windows-kit"
SIGNATURE = re.compile(r"^(?P<ret>.+?) \(\*\)\((?P<params>.*)\)$")


def split_top(parameters):
    depth, current, out = 0, "", []
    for ch in parameters:
        if ch in "(<[":
            depth += 1
        elif ch in ")>]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


def snake(name):
    name = name[len("pfn"):]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def ret_type(ret):
    return {"void": "VOID", "int": "BOOL"}.get(ret, ret)


class DdiTable:
    """One runtime's table: what clang is asked, and what is written from it.

    script        the generator, named in every file's banner
    header        the WDK header the table is in, also named there
    probe         the source clang compiles to find the table
    table         the table's type; record its struct's name in the AST
    device_type   the type of every slot's first parameter, the device
    skip          slot names left out of the table on purpose
    root_slots    slot name -> the root's method that answers it instead
    root_argument the expression a root slot passes the root
    device        the expression that is the device a slot's call goes to
    device_class  the class the methods are declared in
    namespace     the namespace the thunks are in
    prefix        what every file and thunk is named with ("d3d9")
    fill          the function that fills the table
    includes      the thunks' includes
    preamble      the thunks file's opening comment, as lines
    """

    def __init__(self, *, script, header, probe, table, record, device_type, skip, root_slots, root_argument,
                 device, device_class, namespace, prefix, fill, includes, preamble, note_failures=False,
                 trace_calls=False):
        self.script = script
        self.banner = f"// THIS FILE IS GENERATED BY {script} FROM THE WDK'S {header}. DO NOT EDIT.\n"
        self.probe = probe
        self.table = table
        self.record = record
        self.device_type = device_type
        self.skip = skip
        self.root_slots = root_slots
        self.root_argument = root_argument
        self.device = device
        self.device_class = device_class
        self.namespace = namespace
        self.prefix = prefix
        self.fill = fill
        self.includes = includes
        self.preamble = preamble
        # Each HRESULT slot hands its result to DeviceCall::noted, which has
        # the device say which call failed and how.
        self.note_failures = note_failures
        # Each thunk names its slot and arguments to DeviceCall::traced, which
        # makes the call and then hands them to the device's trace_call - or,
        # for a destroy, which forgets the id, to DeviceCall::announced first.
        self.trace_calls = trace_calls

    def dump(self):
        with tempfile.TemporaryDirectory() as scratch:
            source = pathlib.Path(scratch) / "probe.cpp"
            source.write_text(self.probe)
            command = ["clang-cl", "/GR-", "/EHs-c-", "/Zl", "/X", "/D_AMD64_", "/DAMD64", "/D_WIN64",
                       "/DWIN32_LEAN_AND_MEAN", "/DNOMINMAX", f"/clang:-ivfsoverlay{KIT}/overlay.yaml",
                       "-imsvc/windows-kit/km/crt", "-imsvc/windows-kit/um", "-imsvc/windows-kit/sdk-shared",
                       "-imsvc/windows-kit/wdk-shared", "-clang:-std=c++23", "--target=x86_64-pc-windows-msvc",
                       "/Zs", "-Xclang", "-ast-dump=json", "-Xclang", f"-ast-dump-filter={self.table}", str(source)]
            text = subprocess.run(command, capture_output=True, text=True, check=True).stdout
        decoder = json.JSONDecoder()
        at = 0
        while at < len(text):
            while at < len(text) and text[at].isspace():
                at += 1
            if at >= len(text):
                break
            node, at = decoder.raw_decode(text, at)
            if (node.get("kind") == "CXXRecordDecl" and node.get("completeDefinition")
                    and node.get("name") == self.record):
                return [field for field in node["inner"] if field["kind"] == "FieldDecl"]
        raise SystemExit(f"clang reported no definition of {self.table}")

    def entries(self, fields):
        out = []
        for field in fields:
            if self.skip(field["name"]):
                continue
            signature = field["type"].get("desugaredQualType", field["type"]["qualType"])
            signature = signature.replace(" __attribute__((stdcall))", "")
            matched = SIGNATURE.match(signature)
            if not matched:
                raise SystemExit(f"{field['name']}: cannot read {signature!r}")
            parameters = split_top(matched["params"])
            if not parameters or parameters[0] != self.device_type:
                raise SystemExit(f"{field['name']}: first parameter is {parameters[:1]}, not the device")
            out.append((field["name"], field["type"]["qualType"], matched["ret"], parameters))
        return out

    def thunks(self, table):
        lines = [self.banner, *self.preamble, *[f'#include "{path}"' for path in self.includes], "",
                 f"namespace {self.namespace} {{", "", "namespace {", ""]
        for name, _pfn, ret, parameters in table:
            names = ["device"] + [f"a{index}" for index in range(1, len(parameters))]
            declared = ", ".join(f"{kind} {label}" for kind, label in zip(parameters, names))
            arguments = ", ".join(names[1:])
            keyword = "" if ret == "void" else "return "
            lines.append(f"extern \"C\" {ret_type(ret)} APIENTRY avumd_{self.prefix}_{name[3:]}({declared})")
            if name in self.root_slots:
                lines.append(f"{{ {keyword}d3d::umd_binding.root().{self.root_slots[name]}({self.root_argument}); }}")
                lines.append("")
                continue
            if self.note_failures and ret == "HRESULT" and self.trace_calls:
                traced = "".join(f", {label}" for label in names[1:])
                lines.append(f"{{ const d3d::DeviceCall<{self.device_class}> call({self.device});")
                lines.append(f"  return call.noted(\"{name[3:]}\", call.traced(\"{name[3:]}\", "
                             f"&{self.device_class}::{snake(name)}{traced})); }}")
            elif self.note_failures and ret == "HRESULT":
                lines.append(f"{{ {self.device_class} &called = {self.device};")
                lines.append(f"  return d3d::DeviceCall<{self.device_class}>(called).noted(\"{name[3:]}\", "
                             f"called.{snake(name)}({arguments})); }}")
            elif self.trace_calls:
                traced = "".join(f", {label}" for label in names[1:])
                how = "announced" if name.startswith("pfnDestroy") and ret == "void" else "traced"
                lines.append(f"{{ {keyword}d3d::DeviceCall<{self.device_class}>({self.device}).{how}(\"{name[3:]}\", "
                             f"&{self.device_class}::{snake(name)}{traced}); }}")
            else:
                lines.append(f"{{ {keyword}d3d::DeviceCall<{self.device_class}>({self.device}).device()"
                             f".{snake(name)}({arguments}); }}")
            lines.append("")
        lines += ["}  // namespace", "", f"void {self.fill}({self.table} &table)", "{",
                  f'    AV_SCOPE("{self.fill}");']
        for name, _pfn, _ret, _parameters in table:
            lines.append(f"    table.{name} = &avumd_{self.prefix}_{name[3:]};")
        lines += ["}", "", f"}}  // namespace {self.namespace}", ""]
        return "\n".join(lines)

    def methods(self, table):
        lines = [self.banner, f"// Included inside class {self.device_class}: one method per device-table slot.", ""]
        for name, _pfn, ret, parameters in table:
            if name in self.root_slots:
                continue
            declared = ", ".join(parameters[1:])
            lines.append(f"{ret_type(ret)} {snake(name)}({declared});")
        return "\n".join(lines) + "\n"

    def main(self):
        parser = argparse.ArgumentParser()
        parser.add_argument("--check", action="store_true")
        args = parser.parse_args()
        table = self.entries(self.dump())
        files = {f"{self.prefix}_device_thunks.cpp": self.thunks(table),
                 f"{self.prefix}_device_ddi.inc": self.methods(table)}
        if args.check:
            differ = [name for name, text in files.items()
                      if not (OUT / name).exists() or (OUT / name).read_text() != text]
            for name in differ:
                print(f"generated: {name} differs from what {self.script} writes", file=sys.stderr)
            return 1 if differ else 0
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (OUT / name).write_text(text)
        print(f"{pathlib.Path(self.script).stem}: {len(table)} slots -> {OUT}")
        return 0
