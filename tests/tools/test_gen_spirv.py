"""The guest probes' SPIR-V headers are what their GLSL compiles to.

Most tests put a fake glslangValidator on PATH, so what the tool does with a
module - the header it writes, what --check says - is judged without depending
on the real compiler's output; one test runs the real compiler when there is one.
"""
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

from tool_run import ROOT

GEN = ROOT / "tools" / "gen_spirv.py"
SHADERS = ROOT / "src" / "guest" / "probe" / "shaders"

# Words: SPIR-V's magic, a version, the source's length in bytes, then ten
# counting words, so a module spans more than one line of the header.
FAKE_COMPILER = f"""#!{sys.executable}
import pathlib, struct, sys
arguments = sys.argv[1:]
with (pathlib.Path(__file__).parent / "calls.log").open("a") as log:
    log.write(" ".join(arguments) + "\\n")
output = pathlib.Path(arguments[arguments.index("-o") + 1])
source = pathlib.Path(arguments[-1]).read_bytes()
if b"FAIL" in source:
    print(arguments[-1] + ": ERROR: 0:1: 'FAIL' : syntax error")
    sys.exit(2)
if b"ODD" in source:
    output.write_bytes(b"\\x03\\x02\\x23\\x07\\x00")
elif b"NOT_SPIRV" in source:
    output.write_bytes(struct.pack("<2I", 0x12345678, 1))
else:
    output.write_bytes(struct.pack("<13I", 0x07230203, 0x00010000, len(source), *range(10)))
"""


def expected_header(stem, source, length):
    return (f"/* SPIR-V compiled from {source} by glslangValidator -V. Generated by\n"
            f" * tools/gen_spirv.py; edit the GLSL and regenerate, never this file. */\n"
            f"#ifndef AV_{stem.upper()}_SPV_HPP\n"
            f"#define AV_{stem.upper()}_SPV_HPP\n"
            f"\n"
            f"#include <stdint.h>\n"
            f"\n"
            f"namespace av {{\n"
            f"\n"
            f"inline constexpr uint32_t {stem}_spv[] = {{\n"
            f"    0x07230203, 0x00010000, 0x{length:08x}, 0x00000000, 0x00000001, 0x00000002, 0x00000003, 0x00000004,\n"
            f"    0x00000005, 0x00000006, 0x00000007, 0x00000008, 0x00000009,\n"
            f"}};\n"
            f"\n"
            f"inline constexpr uint32_t {stem}_spv_words = 13u;\n"
            f"\n"
            f"}}  // namespace av\n"
            f"\n"
            f"#endif\n")


# The assembler: the same module for assembly, logged beside the compiler's
# calls, its own failure spelled as spirv-as spells one.
FAKE_ASSEMBLER = f"""#!{sys.executable}
import pathlib, struct, sys
arguments = sys.argv[1:]
with (pathlib.Path(__file__).parent / "calls.log").open("a") as log:
    log.write("spirv-as " + " ".join(arguments) + "\\n")
output = pathlib.Path(arguments[arguments.index("-o") + 1])
source = pathlib.Path(arguments[-1]).read_bytes()
if b"FAIL" in source:
    print(arguments[-1] + ":1:1: error: Expected operand")
    sys.exit(1)
output.write_bytes(struct.pack("<13I", 0x07230203, 0x00010000, len(source), *range(10)))
"""


class GenSpirv(unittest.TestCase):
    def setUp(self):
        self.scratch = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.scratch)
        self.shaders = self.scratch / "shaders"
        self.shaders.mkdir()
        self.bin = self.scratch / "bin"
        self.bin.mkdir()
        compiler = self.bin / "glslangValidator"
        compiler.write_text(FAKE_COMPILER)
        compiler.chmod(0o755)
        self.write("double.comp", "void main() {}\n")
        self.write("triangle.vert", "void main() { gl_Position = vec4(0); }\n")
        self.write("solid.frag", "void main() {}\n")

    def write(self, name, text):
        (self.shaders / name).write_text(text)

    def generate(self, *extra, path=None):
        environment = {**os.environ, "PATH": str(path or self.bin)}
        return subprocess.run([sys.executable, "-B", str(GEN), "--shaders", str(self.shaders), *extra],
                              capture_output=True, text=True, env=environment)

    def headers(self):
        return sorted(path.name for path in self.shaders.glob("*_spv.hpp"))

    def test_each_stage_becomes_a_header_holding_its_words_and_their_count(self):
        self.write("notes.txt", "not a shader\n")
        self.write("common.glsl", "not a stage\n")
        result = self.generate()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.headers(), ["double_spv.hpp", "solid_spv.hpp", "triangle_spv.hpp"])
        self.assertEqual((self.shaders / "double_spv.hpp").read_text(),
                         expected_header("double", "double.comp", len("void main() {}\n")))
        self.assertEqual((self.shaders / "triangle_spv.hpp").read_text(),
                         expected_header("triangle", "triangle.vert",
                                         len("void main() { gl_Position = vec4(0); }\n")))
        calls = (self.bin / "calls.log").read_text().splitlines()
        self.assertEqual(len(calls), 3)
        self.assertTrue(all(re.fullmatch(r"-V -o \S+\.spv (double\.comp|triangle\.vert|solid\.frag)", call)
                            for call in calls), calls)

    def test_check_passes_on_what_was_generated_and_writes_nothing(self):
        self.assertEqual(self.generate().returncode, 0)
        before = {name: (self.shaders / name).read_text() for name in self.headers()}
        result = self.generate("--check")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("3 headers match their sources", result.stdout)
        self.assertEqual({name: (self.shaders / name).read_text() for name in self.headers()}, before)

    def test_check_fails_naming_a_header_its_source_no_longer_compiles_to(self):
        self.assertEqual(self.generate().returncode, 0)
        committed = (self.shaders / "solid_spv.hpp").read_text()
        self.write("solid.frag", "void main() { /* longer now */ }\n")
        result = self.generate("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{self.shaders / 'solid_spv.hpp'} differs from what solid.frag compiles to",
                      result.stderr)
        self.assertNotIn("double_spv.hpp", result.stderr)
        self.assertEqual((self.shaders / "solid_spv.hpp").read_text(), committed)

    def test_check_fails_naming_a_hand_edited_header(self):
        self.assertEqual(self.generate().returncode, 0)
        header = self.shaders / "double_spv.hpp"
        header.write_text(header.read_text().replace("13u", "12u"))
        result = self.generate("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("double_spv.hpp differs from what double.comp compiles to", result.stderr)

    def test_check_fails_naming_a_missing_header_without_writing_it(self):
        result = self.generate("--check")
        self.assertEqual(result.returncode, 1)
        for name in ("double_spv.hpp", "solid_spv.hpp", "triangle_spv.hpp"):
            self.assertIn(f"{self.shaders / name} is missing", result.stderr)
        self.assertEqual(self.headers(), [])

    def test_a_header_whose_source_is_gone_fails_the_check_and_generating_removes_it(self):
        self.assertEqual(self.generate().returncode, 0)
        (self.shaders / "triangle.vert").unlink()
        result = self.generate("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{self.shaders / 'triangle_spv.hpp'} has no source", result.stderr)
        result = self.generate()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.headers(), ["double_spv.hpp", "solid_spv.hpp"])

    def test_without_glslang_validator_both_modes_fail_saying_so(self):
        empty = self.scratch / "empty"
        empty.mkdir()
        for extra in (("--check",), ()):
            result = self.generate(*extra, path=empty)
            self.assertEqual(result.returncode, 1, extra)
            self.assertIn("glslangValidator not found on PATH", result.stderr)
        self.assertEqual(self.headers(), [])

    def test_a_shader_that_does_not_compile_is_named_and_no_header_is_written(self):
        self.write("triangle.vert", "FAIL\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("triangle.vert: glslangValidator failed", result.stderr)
        self.assertIn("'FAIL' : syntax error", result.stderr)
        self.assertEqual(self.headers(), [])

    def test_output_that_is_not_spirv_is_refused(self):
        self.write("solid.frag", "ODD\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("solid.frag: glslangValidator wrote 5 bytes, not whole SPIR-V words", result.stderr)
        self.write("solid.frag", "NOT_SPIRV\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("solid.frag: glslangValidator wrote magic 0x12345678, not SPIR-V", result.stderr)
        self.assertEqual(self.headers(), [])

    def assembler(self):
        assembler = self.bin / "spirv-as"
        assembler.write_text(FAKE_ASSEMBLER)
        assembler.chmod(0o755)

    def test_an_opencl_kernel_s_assembly_becomes_a_header_said_to_be_assembled(self):
        self.assembler()
        self.write("vector_add.spvasm", "OpCapability Kernel\n")
        result = self.generate()
        self.assertEqual(result.returncode, 0, result.stderr)
        header = (self.shaders / "vector_add_spv.hpp").read_text()
        expected = expected_header("vector_add", "vector_add.spvasm", len("OpCapability Kernel\n"))
        made = ("/* SPIR-V assembled from vector_add.spvasm by spirv-as --target-env spv1.0. Generated\n"
                " * by tools/gen_spirv.py; edit the assembly and regenerate, never this file. */\n")
        self.assertEqual(header, made + expected.split("\n", 2)[2])
        calls = [call for call in (self.bin / "calls.log").read_text().splitlines() if call.startswith("spirv-as")]
        self.assertEqual(len(calls), 1)
        self.assertRegex(calls[0], r"^spirv-as --target-env spv1\.0 -o \S+\.spv vector_add\.spvasm$")
        self.assertEqual(self.generate("--check").returncode, 0)

    def test_without_spirv_as_assembly_fails_saying_so_and_glsl_alone_does_not_need_it(self):
        self.assertEqual(self.generate().returncode, 0)
        self.write("vector_add.spvasm", "OpCapability Kernel\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("spirv-as not found on PATH", result.stderr)
        self.assertNotIn("vector_add_spv.hpp", self.headers())

    def test_assembly_that_does_not_assemble_is_named(self):
        self.assembler()
        self.write("vector_add.spvasm", "FAIL\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("vector_add.spvasm: spirv-as failed", result.stderr)
        self.assertIn("Expected operand", result.stderr)

    def test_two_stages_that_would_write_one_header_are_refused(self):
        self.write("solid.vert", "void main() {}\n")
        result = self.generate()
        self.assertEqual(result.returncode, 1)
        self.assertIn("solid.frag and solid.vert would both write solid_spv.hpp", result.stderr)
        self.assertEqual(self.headers(), [])


@unittest.skipUnless(shutil.which("glslangValidator"), "glslangValidator is not installed")
class RealCompiler(unittest.TestCase):
    def test_the_committed_headers_are_what_the_real_compiler_makes_of_the_sources(self):
        scratch = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, scratch)
        for source in ("double.comp", "triangle.vert", "solid.frag"):
            shutil.copy(SHADERS / source, scratch / source)
        result = subprocess.run([sys.executable, "-B", str(GEN), "--shaders", str(scratch)],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        for stem in ("double", "triangle", "solid"):
            header = (scratch / f"{stem}_spv.hpp").read_text()
            self.assertEqual(header, (SHADERS / f"{stem}_spv.hpp").read_text(), stem)
            words = re.findall(r"0x[0-9a-f]{8}", header)
            self.assertEqual(words[0], "0x07230203", stem)
            self.assertIn(f"{stem}_spv_words = {len(words)}u;", header)


if __name__ == "__main__":
    unittest.main()


@unittest.skipUnless(shutil.which("glslangValidator") and shutil.which("spirv-as"), "spirv-as is not installed")
class RealAssembler(unittest.TestCase):
    def test_the_committed_kernel_header_is_what_the_real_assembler_makes_of_its_assembly(self):
        scratch = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, scratch)
        shutil.copy(SHADERS / "vector_add.spvasm", scratch / "vector_add.spvasm")
        result = subprocess.run([sys.executable, "-B", str(GEN), "--shaders", str(scratch)],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        header = (scratch / "vector_add_spv.hpp").read_text()
        self.assertEqual(header, (SHADERS / "vector_add_spv.hpp").read_text())
        self.assertEqual(re.findall(r"0x[0-9a-f]{8}", header)[0], "0x07230203")
