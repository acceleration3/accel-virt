FloatBlitPass::FloatBlitPass()
    : vertex_(nullptr), pixel_(nullptr), constants_(nullptr), recorder_(nullptr), target_(nullptr),
      target_view_(nullptr), copy_(nullptr), target_width_(0u), target_height_(0u), target_format_(0u),
      copy_width_(0u), copy_height_(0u), copy_format_(0u)
{
    AV_SCOPE("FloatBlitPass::FloatBlitPass");
}

FloatBlitPass::~FloatBlitPass()
{
    AV_SCOPE("FloatBlitPass::~FloatBlitPass");
    release();
}

void FloatBlitPass::release()
{
    AV_SCOPE("FloatBlitPass::release");
    drop(copy_);
    drop(target_view_);
    drop(target_);
    drop(recorder_);
    drop(constants_);
    drop(pixel_);
    drop(vertex_);
    target_width_ = target_height_ = target_format_ = 0u;
    copy_width_ = copy_height_ = copy_format_ = 0u;
}

bool FloatBlitPass::arm(ID3D11Device5 *device)
{
    AV_SCOPE("FloatBlitPass::arm");
    if (recorder_ != nullptr) return true;
    const D3D11_BUFFER_DESC constants = {sizeof(RegionConstants), D3D11_USAGE_DEFAULT, D3D11_BIND_CONSTANT_BUFFER, 0u,
                                         0u, 0u};
    if (FAILED(device->CreateVertexShader(vertex_bytecode, sizeof(vertex_bytecode), nullptr, &vertex_)) ||
        FAILED(device->CreatePixelShader(pixel_bytecode, sizeof(pixel_bytecode), nullptr, &pixel_)) ||
        FAILED(device->CreateBuffer(&constants, nullptr, &constants_)) ||
        FAILED(device->CreateDeferredContext(0u, &recorder_))) {
        release();
        return false;
    }
    return true;
}

bool FloatBlitPass::prepare_target(ID3D11Device5 *device, uint32_t width, uint32_t height, uint32_t format)
{
    AV_SCOPE("FloatBlitPass::prepare_target");
    if (target_view_ != nullptr && target_width_ == width && target_height_ == height && target_format_ == format)
        return true;
    drop(target_view_);
    drop(target_);
    const D3D11_TEXTURE2D_DESC described = {width, height, 1u, 1u, static_cast<DXGI_FORMAT>(format), {1u, 0u},
                                           D3D11_USAGE_DEFAULT, D3D11_BIND_RENDER_TARGET | D3D11_BIND_SHADER_RESOURCE,
                                           0u, 0u};
    if (FAILED(device->CreateTexture2D(&described, nullptr, &target_)) ||
        FAILED(device->CreateRenderTargetView(target_, nullptr, &target_view_))) {
        drop(target_view_);
        drop(target_);
        return false;
    }
    target_width_ = width;
    target_height_ = height;
    target_format_ = format;
    return true;
}

bool FloatBlitPass::prepare_copy(ID3D11Device5 *device, uint32_t width, uint32_t height, uint32_t format)
{
    AV_SCOPE("FloatBlitPass::prepare_copy");
    if (copy_ != nullptr && copy_width_ == width && copy_height_ == height && copy_format_ == format) return true;
    drop(copy_);
    const D3D11_TEXTURE2D_DESC described = {width, height, 1u, 1u, static_cast<DXGI_FORMAT>(format), {1u, 0u},
                                            D3D11_USAGE_DEFAULT, D3D11_BIND_SHADER_RESOURCE, 0u, 0u};
    if (FAILED(device->CreateTexture2D(&described, nullptr, &copy_))) {
        copy_ = nullptr;
        return false;
    }
    copy_width_ = width;
    copy_height_ = height;
    copy_format_ = format;
    return true;
}

ID3D11Texture2D *FloatBlitPass::draw(ID3D11Device5 *device, ID3D11DeviceContext4 *context, ID3D11Texture2D *source,
                                     uint32_t subresource, const Rectangle &from, uint32_t width, uint32_t height,
                                     uint32_t target_format, bool encode)
{
    AV_SCOPE("FloatBlitPass::draw");
    D3D11_TEXTURE2D_DESC origin = {};
    source->GetDesc(&origin);
    const uint32_t right = from.right < origin.Width ? from.right : origin.Width;
    const uint32_t bottom = from.bottom < origin.Height ? from.bottom : origin.Height;
    if (right <= from.left || bottom <= from.top || origin.SampleDesc.Count != 1u) return nullptr;
    if (!arm(device) || !prepare_target(device, width, height, target_format)) return nullptr;
    const uint32_t across = right - from.left;
    const uint32_t down = bottom - from.top;
    const bool     sampled = (origin.BindFlags & D3D11_BIND_SHADER_RESOURCE) != 0u && origin.ArraySize == 1u &&
                         origin.MipLevels == 1u && subresource == 0u;
    ID3D11Texture2D *input = source;
    uint32_t         left = from.left;
    uint32_t         top = from.top;
    if (!sampled) {
        if (!prepare_copy(device, across, down, origin.Format)) return nullptr;
        const D3D11_BOX region = {from.left, from.top, 0u, right, bottom, 1u};
        recorder_->CopySubresourceRegion(copy_, 0u, 0u, 0u, 0u, source, subresource, &region);
        input = copy_;
        left = 0u;
        top = 0u;
    }
    ID3D11ShaderResourceView *view = nullptr;
    if (FAILED(device->CreateShaderResourceView(input, nullptr, &view))) {
        ID3D11CommandList *abandoned = nullptr;
        if (SUCCEEDED(recorder_->FinishCommandList(FALSE, &abandoned))) abandoned->Release();
        return nullptr;
    }
    const RegionConstants constants = {left, top, across, down, width, height, encode ? 1u : 0u, 0u};
    const D3D11_VIEWPORT  viewport = {0.0f, 0.0f, static_cast<float>(width), static_cast<float>(height), 0.0f, 1.0f};
    recorder_->UpdateSubresource(constants_, 0u, nullptr, &constants, 0u, 0u);
    recorder_->IASetPrimitiveTopology(D3D11_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
    recorder_->VSSetShader(vertex_, nullptr, 0u);
    recorder_->PSSetShader(pixel_, nullptr, 0u);
    recorder_->PSSetConstantBuffers(0u, 1u, &constants_);
    recorder_->PSSetShaderResources(0u, 1u, &view);
    recorder_->RSSetViewports(1u, &viewport);
    recorder_->OMSetRenderTargets(1u, &target_view_, nullptr);
    recorder_->Draw(fullscreen_vertices, 0u);
    ID3D11CommandList *list = nullptr;
    const bool         recorded = SUCCEEDED(recorder_->FinishCommandList(FALSE, &list));
    view->Release();
    if (!recorded) return nullptr;
    context->ExecuteCommandList(list, TRUE);
    list->Release();
    return target_;
}

