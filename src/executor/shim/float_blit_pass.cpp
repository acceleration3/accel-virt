struct RegionConstants {
    uint32_t left;
    uint32_t top;
    uint32_t across;
    uint32_t down;
    uint32_t width;
    uint32_t height;
    uint32_t encode;
    uint32_t reserved;
};

constexpr uint32_t fullscreen_vertices = 3u;

template <typename Interface> void drop(Interface *&object)
{
    AV_SCOPE("drop");
    if (object != nullptr) object->Release();
    object = nullptr;
}

